h("5.4 Component D: plastic leakage estimation", 2)
p("Components A and B answer where material is. Component D answers how much "
  "is generated and how much escapes, which is the quantity the concept "
  "note's leakage indicator requires and the one no detection layer can "
  "supply. The distinction of provenance is maintained throughout: satellite "
  "detection measures where material is and how much of it there is; "
  "gravimetric sorting on the ground measures what share of it is plastic; "
  "terrain and hydrology models say where it goes. Component D is the "
  "bookkeeping that connects the second to the third, and it contains no "
  "pixel.")

h("5.4.1 The chain, and the step most estimates omit", 3)
p("Population is carried through six multiplications:")
bullet("generated = population \u00d7 rate \u00d7 365.25 [t yr\u207b\u00b9 MSW]")
bullet("plastic = generated \u00d7 plastic share")
bullet("uncollected = plastic \u00d7 (1 \u2212 collection), split urban/rural")
bullet("burned = uncollected \u00d7 open-burning fraction \u2014 DESTROYED, not leaked")
bullet("to environment = (uncollected \u2212 burned) \u00d7 leakage fraction "
       "+ collected \u00d7 litter rate")
bullet("to water = to environment \u00d7 transport probability")

p("The fourth step is the one that distinguishes this from a naive estimate. "
  "'Uncollected' is routinely treated as a synonym for 'leaked', which it is "
  "not: in low-income settings most uncollected household waste is burned in "
  "the open or buried in a household pit, and burned plastic is destroyed as "
  "macro-debris \u2014 it becomes an air-quality and health problem instead, "
  "which this module does not attempt to quantify. Cottom, Cook & Velis "
  "(2024) find open burning to be the dominant fate of uncollected plastic "
  "across the Global South, exceeding unburned debris emissions. Omitting the "
  "step roughly doubles the answer and is the most common reason national "
  "leakage estimates come out too high.")

h("5.4.2 Population, and a 20% error that the geometry conceals", 3)
p("WorldPop's gin_pd_2020_1km_UNadj product is a population DENSITY surface "
  "\u2014 persons per square kilometre \u2014 not a count per pixel, and the "
  "'1 km' in its name invites the opposite reading. Summing its pixels gives "
  "15.70 million against a 2020 population of about 13.13 million. The gap is "
  "geometry: the grid is 0.00833\u00b0, which is 1 km north\u2013south but "
  "only about 0.92 km east\u2013west at Guinea's latitudes, so a pixel covers "
  "roughly 0.84 km\u00b2. Density is therefore multiplied by each pixel's "
  "true area, computed on the WGS84 ellipsoid and varying with latitude. The "
  "error is silent, and inflates every downstream tonnage by a fifth in the "
  "direction that makes the problem look worse.")

h("5.4.3 Urban and rural, and an out-of-sample check on the split", 3)
p("The split exists only because the collection survey is reported that way, "
  "and the two rates are far apart: 23.7% urban against 2.1% rural (JICA "
  "2022, via the World Bank What a Waste database). Collapsing them to the "
  "9.7% national average would discard the structure that drives the spatial "
  "pattern. The threshold follows the UN-endorsed Degree of Urbanisation "
  "(Dijkstra et al. 2021), which sets an urban cluster at \u2265300 persons "
  "km\u207b\u00b2 and an urban centre at \u22651,500. The survey does not "
  "state which definition its 'urban area' matches, so the choice is treated "
  "as an uncertainty and sampled across that range rather than fixed. "
  "DEGURBA's spatial contiguity rule is not applied, because the mask only "
  "has to route each pixel to one of two collection rates; the simplification "
  "is recorded rather than hidden.")

h("5.4.4 Why errors are not combined in quadrature", 3)
p("The obvious way to combine regional uncertainties is the square root of "
  "the sum of squares. That is wrong here, and wrong in a way that worsens "
  "the more finely the country is subdivided. Quadrature assumes independent "
  "errors; these errors are not merely correlated but identical. Every region "
  "is driven by the same national generation rate, the same plastic share, "
  "the same collection survey, the same burning fraction. If the true plastic "
  "share is 15% rather than 4%, it is 15% in Bok\u00e9 AND Kankan AND "
  "Conakry simultaneously. Regional errors move in lockstep rather than "
  "partially cancelling, so quadrature manufactures spurious cancellation "
  "\u2014 and dividing a country into more pieces cannot make its total "
  "better known.")

p("Uncertainty is therefore propagated by Monte Carlo with each national "
  "parameter drawn ONCE PER ITERATION and applied to every region and pixel "
  "in that iteration. Regional totals then sum exactly to the national total "
  "within each iteration and the correlation is carried by construction. "
  "\u00a77.6 reports the size of the error this avoids.")

h("5.4.5 Plastic share as a scenario, not a distribution", 3)
p("One parameter moves the answer by more than all the others combined, and "
  "it is not propagated as a distribution. Guinea's only nationally "
  "representative waste composition figure gives plastic at 4.0% of municipal "
  "solid waste, from a 2007 UNSD collection; recent characterisation for "
  "Conakry gives 15\u201322%. Averaging over that disagreement would produce "
  "a number belonging to neither world and would conceal that the "
  "disagreement is about evidence rather than noise. Every result is "
  "therefore reported under each scenario separately, with the range visible.")

h("5.4.6 Per-site allocation", 3)
p("The mobilisation model of \u00a75.3.7 ranks detected sites by how likely "
  "their contents are to reach a watercourse, using a dimensionless size-class "
  "mass proxy. It can say site A outranks site B; it cannot say how many "
  "tonnes either contributes, which is the question a clean-up budget is "
  "written against. Component D attaches tonnes by catchment allocation: the "
  "population within 5 km of a site \u2014 the distance band used in the "
  "UNEP/IUCN hotspotting guidance, consistent with informal disposal served "
  "by headloading and handcart rather than municipal haulage \u2014 run "
  "through the same chain.")

p("Two properties are deliberate. Catchments OVERLAP, and summing "
  "independently computed catchments would push the site total above the "
  "national total, an impossibility that would nonetheless look plausible in "
  "a table; each pixel's population is therefore divided among the sites "
  "claiming it. And no mass is estimated from imagery: \u00a77.3.1 measured "
  "these sites at roughly 14 m across, sub-pixel at Sentinel-2's 10 m bands, "
  "and Appendix C found no polymer absorption feature at these scales, so "
  "there is no spectral route from an image to a mass. Multiplying area by an "
  "assumed depth and density would produce a number whose precision is "
  "fictitious. The satellite contributes the LOCATION, which is what it "
  "measures.")

h("5.5 Statistical treatment", 2)

p("Average precision is reported rather than area under the receiver operating "
  "characteristic curve wherever prevalence is low, because ROC-AUC is "
  "optimistic under class imbalance (Saito and Rehmsmeier, 2015). The no-skill "
  "baseline for average precision is the positive prevalence, not 0.5, and it "
  "is stated wherever an average precision is quoted.")

p("Confidence intervals come from a cluster bootstrap resampling whole label "
  "cells, because one cell can contribute several dump points and points "
  "within a cell are not independent. For component B the resampling unit is a "
  "250 m spatial block rather than a window: windows within a block overlap "
  "the same ground, and resampling them independently would treat correlated "
  "observations as independent and yield intervals far too narrow.")

p("Comparisons between methods use a paired bootstrap computing the difference "
  "within each replicate, because comparing overlapping marginal confidence "
  "intervals is a known error (Schenker and Gentleman, 2001). Model "
  "comparisons use 2,000 resamples.")

p("Any fitted model is evaluated under spatial blocking (Roberts et al., "
  "2017). For component B the blocks are 1 km. For the Sentinel-2 index tests "
  "the blocks are the eight administrative regions. For the hyperspectral test "
  "the block is the dumpsite itself, so that a site appearing in several "
  "scenes lands wholly in one fold; blocking on scene or detector row would "
  "leak a site between training and test.")

p("One post hoc choice is declared rather than hidden. Index orientation was "
  "selected after the fact: both an index and its negation were scored and the "
  "better reported. This is a two-way selection on the same data and mildly "
  "inflates absolute values. It does not affect the conclusions, which rest on "
  "relative comparisons against controls scored under the identical rule.")

