# The blind grid is recomputed from the labels rather than quoted, because it
# is the single most consequential number in component B and the one most
# easily misread. See §7.2.6.
def _blind_grid():
    import numpy as np
    from sklearn.metrics import roc_auc_score, average_precision_score

    d = json.loads((MQ / "regions" / "conakry_blindgrid_review.geojson")
                   .read_text(encoding="utf-8"))
    P = [f["properties"] for f in d["features"]]
    y = np.array([int(p["label"]) for p in P])
    s = np.array([float(p["model_score"]) for p in P])
    half = np.array([p["half"] for p in P])
    ops = []
    for t in (0.90, 0.70, 0.50):
        m = s >= t
        tp = int((y[m] == 1).sum())
        ops.append({"threshold": t, "flagged": int(m.sum()), "true": tp,
                    "false": int(m.sum()) - tp,
                    "precision": tp / max(int(m.sum()), 1),
                    "recall": tp / int(y.sum())})
    east = half == "east"
    return {
        "n": len(y), "n_pos": int(y.sum()), "base_rate": float(y.mean()),
        "roc_auc": float(roc_auc_score(y, s)),
        "avg_precision": float(average_precision_score(y, s)),
        "operating_points": ops,
        "east_n": int(east.sum()),
        "east_roc_auc": float(roc_auc_score(y[east], s[east])),
        "east_avg_precision": float(average_precision_score(y[east], s[east])),
    }


