def _river():
    """
    Re-derive each tile's verdict from the recorded fields.

    The run file is a faithful record of what the code did at the time, and
    two checks were added after it was written: a missing water mask is not a
    pass, and an NDVI threshold outside [-1, 1] proves the water population is
    not water. Reclassifying here rather than rewriting the run file keeps the
    record intact and makes the correction auditable.
    """
    import math
    rows = {r["aoi"]: r for r in RIVER_RAW.get("results", [])}.values()
    out = {"valid": [], "no_water_mask": [], "implausible": [], "guard": []}
    for r in rows:
        if not r.get("assessed"):
            out["guard"].append(r); continue
        t, nd = r.get("threshold_fdi"), r.get("threshold_ndvi")
        if t is None or (isinstance(t, float) and math.isnan(t)):
            out["no_water_mask"].append(r); continue
        if nd is None or (isinstance(nd, float) and math.isnan(nd)) or abs(nd) > 1.0:
            out["implausible"].append(r); continue
        out["valid"].append(r)
    km = lambda k: sum(x.get("length_km", 0) for x in out[k])   # noqa: E731
    v = out["valid"]
    thr = sorted(x["threshold_fdi"] for x in v)
    patches = sum(int(x.get("n_patches") or 0) for x in v)
    return {
        "n_tiles": len(rows), "total_km": sum(km(k) for k in out),
        "counts": {k: len(out[k]) for k in out},
        "km": {k: km(k) for k in out},
        "n_valid": len(v), "valid_km": km("valid"), "patches": patches,
        "tiles_with_patches": sum(1 for x in v if (x.get("n_patches") or 0) > 0),
        "systems_assessed": len({x["main_riv"] for x in v}),
        "systems_with_patches": len({x["main_riv"] for x in v
                                     if (x.get("n_patches") or 0) > 0}),
        "thr_med": thr[len(thr) // 2] if thr else float("nan"),
        "thr_min": thr[0] if thr else float("nan"),
        "thr_max": thr[-1] if thr else float("nan"),
        "failures": len(RIVER_RAW.get("failures", [])),
    }


