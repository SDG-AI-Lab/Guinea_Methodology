def fig(names, caption, width=6.2):
    """
    Place a figure and its numbered caption.

    `names` may be a single stem or a list. Each stem is looked up first in
    `runs/figures/` (regenerated by the characterisation notebook, so always
    current) and then in `runs/figures_doc/` (the archived FDI figures, whose
    notebook outputs are not retained in the tree).
    """
    _fig_n[0] += 1
    if isinstance(names, str):
        names = [names]
    placed = 0
    for name in names:
        for base in (FIGS, FIGS_DOC, FIGS_MQ):
            path = base / f"{name}.png"
            if path.exists():
                doc.add_picture(str(path), width=Inches(width))
                doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
                placed += 1
                break
        else:
            print(f"  ! missing figure {name}")
    if not placed:
        _fig_n[0] -= 1
        return
    c = doc.add_paragraph(f"Figure {_fig_n[0]}. {caption}", style="Caption")
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER


def table(headers, rows, caption=None):
    """Caption first, then the table — the convention in the approved docs."""
    if caption:
        _tab_n[0] += 1
        c = doc.add_paragraph(f"Table {_tab_n[0]}. {caption}", style="Caption")
        c.alignment = WD_ALIGN_PARAGRAPH.LEFT
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    for i, head in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = str(head)
        for r in cell.paragraphs[0].runs:
            r.bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = "" if v is None else str(v)
    doc.add_paragraph()
    return t


def pct(x, d=1):
    return f"{100 * x:.{d}f}%"


def f3(x):
    return f"{x:.3f}"


