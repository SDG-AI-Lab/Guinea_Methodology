def _prevalence_matched(recall, fpr, base):
    """Precision this model would show at another study's base rate.

    Precision is not a property of a classifier alone: it falls automatically
    as positives become rarer. Comparing raw precision across two studies with
    different prevalence therefore measures the difference in their test sets
    as much as in their models. Recall and false-positive rate ARE invariant to
    prevalence, so precision can be recomputed at any base rate from them:

        precision = (recall * p) / (recall * p + fpr * (1 - p))

    This is Bayes' rule written in the quantities a confusion matrix reports,
    and it is the standard correction for comparing across prevalences.
    """
    tp = recall * base
    fp = fpr * (1.0 - base)
    return tp / (tp + fp) if (tp + fp) else float("nan")

