from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional

HERE = Path(__file__).resolve().parent
# One level deeper than the numbered original: `runs/`,
# `manual_qa/` and the frozen models all live in the parent
# package directory, so paths climb one extra level.
TOOL = HERE.parent
PROJECT_ROOT = TOOL.parent
COVERAGE_JSON = TOOL / "runs" / "hyperspectral_coverage" / "coverage_summary.json"
ENMAP_ITEMS = TOOL / "runs" / "hyperspectral_coverage" / "enmap_items.json"
OUT_DIR = TOOL / "runs" / "enmap_scenes"

LOGIN_URL = "https://sso.eoc.dlr.de/eoc/auth/login"

# ASSET-NAMING TRAP, cost one wasted download:
# the STAC asset called "swir" is NOT the SWIR cube -- it is
# `QL_SWIR_COG.TIF`, a 4-band uint8 RGB *quicklook* (2.8 MB). Likewise "vnir".
# Everything prefixed QL_ is a preview. The actual 224-band L2A cube is the
# asset named **"image"** (`SPECTRAL_IMAGE_COG.TIF`), int16, hundreds of MB.
# Ask for "swir" expecting spectra and you get a browse image that looks
# plausible in a viewer and has no bands to unmix.
DEFAULT_ASSETS = ["image", "metadata", "quality_cloud"]


def load_credentials() -> tuple[str, str]:
    from dotenv import load_dotenv
    load_dotenv(dotenv_path=PROJECT_ROOT / ".env", override=True)
    user = os.getenv("DLR_EOC_USERNAME")
    pwd = os.getenv("DLR_EOC_PASSWORD")
    if not user or not pwd:
        print("Missing DLR_EOC_USERNAME / DLR_EOC_PASSWORD in .env.\n"
              "Add them to "
              f"{PROJECT_ROOT / '.env'} and re-run. See this file's docstring.")
        raise SystemExit(2)
    return user, pwd


def cas_login(session, service_url: str, user: str, pwd: str) -> bool:
    """
    Standard CAS form login. The login page carries `execution` and `_csrf`
    hidden fields that must be echoed back, and `_eventId=submit`.
    """
    r = session.get(LOGIN_URL, params={"service": service_url}, timeout=120)
    html = r.text

    def field(name: str) -> Optional[str]:
        m = re.search(rf'name="{name}"\s+value="([^"]*)"', html)
        return m.group(1) if m else None

    execution, csrf = field("execution"), field("_csrf")
    if not execution:
        print("  ! could not find CAS `execution` field — login page changed?")
        return False

    payload = {"username": user, "password": pwd, "execution": execution,
               "_eventId": "submit", "geolocation": "", "deviceFingerprint": ""}
    if csrf:
        payload["_csrf"] = csrf

    r2 = session.post(LOGIN_URL, params={"service": service_url}, data=payload,
                      timeout=120, allow_redirects=True)

    # A failed login re-serves the login form; a successful one lands on the
    # service (or at least stops being the SSO host).
    if "sso.eoc.dlr.de" in r2.url and ("password" in r2.text.lower()
                                       or "execution" in r2.text):
        print("  ! login rejected — check DLR_EOC_USERNAME / DLR_EOC_PASSWORD")
        return False
    return True


def select_scenes(limit: int, max_cloud: float,
                  match: Optional[List[str]] = None) -> List[Dict]:
    """
    EnMAP scenes containing a labelled dump point, cleanest first.

    `match` selects explicit scenes by id substring. That matters because
    ranking purely by dump-point count picks the big Conakry scenes, which
    largely re-image the SAME sites on different dates — good for temporal
    replication, useless for geographic spread. Choosing scenes by hand lets a
    run cover several regions instead of one city repeatedly.
    """
    with open(COVERAGE_JSON, "r", encoding="utf-8") as fh:
        cov = json.load(fh)
    items = cov["missions"]["EnMAP"]["items"]

    def cloud(it):
        try:
            return float(it["cloud_cover"])
        except (TypeError, ValueError):
            return 999.0

    if match:
        keep = [it for it in items if any(m in it["id"] for m in match)]
        missing = [m for m in match
                   if not any(m in it["id"] for it in items)]
        for m in missing:
            print(f"  ! no scene matches {m!r}")
        keep.sort(key=lambda it: (cloud(it), -it["n_dump_points"]))
        return keep

    keep = [it for it in items if cloud(it) <= max_cloud]
    # Cleanest first, then the scene touching the most dump points.
    keep.sort(key=lambda it: (cloud(it), -it["n_dump_points"]))
    return keep[:limit] if limit > 0 else keep


def asset_urls(scene_id: str, wanted: List[str]) -> Dict[str, str]:
    with open(ENMAP_ITEMS, "r", encoding="utf-8") as fh:
        items = json.load(fh)
    for it in items:
        if it["id"] == scene_id:
            return {k: v["href"] for k, v in (it.get("assets") or {}).items()
                    if k in wanted}
    return {}


def download(session, url: str, dest: Path) -> bool:
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists() and dest.stat().st_size > 0:
        print(f"      exists, skipping ({dest.stat().st_size / 1e6:.1f} MB)")
        return True
    with session.get(url, stream=True, timeout=600) as r:
        ctype = r.headers.get("Content-Type", "")
        if "text/html" in ctype:
            print(f"      ! got HTML not data — session not authenticated")
            return False
        total = int(r.headers.get("Content-Length", 0))
        got = 0
        tmp = dest.with_suffix(dest.suffix + ".part")
        with open(tmp, "wb") as fh:
            for chunk in r.iter_content(1 << 20):
                fh.write(chunk)
                got += len(chunk)
                if total and got % (50 << 20) < (1 << 20):
                    print(f"      {got / 1e6:.0f}/{total / 1e6:.0f} MB")
        tmp.rename(dest)
        print(f"      done {got / 1e6:.1f} MB -> {dest.name}")
    return True


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=1,
                    help="scenes to download (0 = all). Default 1 — these are large.")
    ap.add_argument("--max-cloud", type=float, default=10.0)
    ap.add_argument("--assets", default=",".join(DEFAULT_ASSETS))
    ap.add_argument("--match", default="",
                    help="comma-separated scene-id substrings; overrides --limit")
    ap.add_argument("--list", action="store_true",
                    help="show candidate scenes and exit, no credentials needed")
    args = ap.parse_args()

    if not COVERAGE_JSON.exists():
        print(f"Missing {COVERAGE_JSON} — run 10_hyperspectral_coverage.py first.")
        return 1

    match = [m.strip() for m in args.match.split(",") if m.strip()]
    scenes = select_scenes(0 if args.list else args.limit, args.max_cloud, match)
    print(f"EnMAP scenes on labelled dumps with cloud <= {args.max_cloud:.0f}%: "
          f"{len(scenes)}")
    for s in scenes:
        print(f"  {s['datetime'][:10]}  cloud={str(s['cloud_cover']):>3}%  "
              f"dumps={s['n_dump_points']:>2}  swir={s.get('swir_status')}  {s['id'][:52]}")
    if args.list:
        return 0

    try:
        import requests
    except ImportError:
        print("`requests` is required: pip install requests")
        return 1

    user, pwd = load_credentials()
    wanted = [a.strip() for a in args.assets.split(",") if a.strip()]

    session = requests.Session()
    session.headers["User-Agent"] = "GEDH-DPWMS/1.0"

    first_url = None
    for s in scenes:
        urls = asset_urls(s["id"], wanted)
        if urls:
            first_url = next(iter(urls.values()))
            break
    if not first_url:
        print("No matching assets found for the selected scenes.")
        return 1

    print("\nAuthenticating against DLR EOC SSO ...")
    if not cas_login(session, first_url, user, pwd):
        return 1
    print("  authenticated")

    ok = True
    for s in scenes:
        print(f"\n{s['id'][:60]}  (cloud {s['cloud_cover']}%, "
              f"{s['n_dump_points']} dump points)")
        urls = asset_urls(s["id"], wanted)
        if not urls:
            print("    ! no assets matched")
            continue
        for name, url in urls.items():
            ext = Path(url.split("?")[0]).suffix or ".bin"
            dest = OUT_DIR / s["id"] / f"{name}{ext}"
            print(f"    {name}")
            ok &= download(session, url, dest)

    print(f"\nScenes under {OUT_DIR}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
