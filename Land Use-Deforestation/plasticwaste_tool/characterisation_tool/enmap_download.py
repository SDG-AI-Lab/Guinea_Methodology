"""
15 — Download EnMAP L2A scenes that cover labelled Guinean dumpsites.

The DLR EOC STAC catalogue at
`https://geoservice.dlr.de/eoc/ogc/stac/v1/collections/ENMAP_HSI_L2A` is open
and needs no account — script 10 already used it to find that 27 EnMAP scenes
sit on labelled dump points, 21 of them below 10% cloud.

**The catalogue was never the blocker. The assets are.** Every asset URL under
`download.geoservice.dlr.de` returns HTTP 200 but serves an HTML login page,
redirecting to `sso.eoc.dlr.de`. HTTP Basic auth is rejected (403, no
WWW-Authenticate header), so it is CAS session auth: log in once, keep the
cookie, then the asset URLs serve real bytes.

CREDENTIALS
-----------
Add to `.env` (same file as the other secrets — never pass them on the
command line, where they end up in shell history):

    DLR_EOC_USERNAME=your_eoc_username
    DLR_EOC_PASSWORD=your_eoc_password

SIZE WARNING
------------
EnMAP L2A products are large — the SWIR cube alone is typically several hundred
MB per scene. This script defaults to **one** scene so the first run is cheap
and verifiable. Raise `--limit` deliberately.

Usage:
    python plasticwaste_tool/15_enmap_download.py --list
    python plasticwaste_tool/15_enmap_download.py --limit 1
    python plasticwaste_tool/15_enmap_download.py --limit 1 --assets swir,metadata
"""
