"""
18 — Extract EnMAP spectra at labelled dumpsites and matched non-dumpsites.

THE DECISIVE TEST FOR PATH B
----------------------------
Tasks 1-3 and the extent measurement have narrowed the question to one thing:

  Task 1  hyperspectral coverage over Guinea is excellent (110/111 dump points
          have a low-cloud EMIT or EnMAP scene), and unlike Sentinel-2 these
          sensors resolve both diagnostic C-H features (1215 nm, 1730 nm)
  Task 2  Sentinel-2 plastic indices detect bare ground, not plastic
  Task 3  FDI on land is the same bare-ground proxy
  extent  dumpsites are ~14 m -> 0.22 of an EnMAP pixel; every site is
          sub-pixel, so no pixel contains only dump

So the remaining question is not "can we see a dump's spectrum" - we cannot,
there is no pure dump pixel anywhere. It is:

    Does a ~23%-dumpsite pixel differ spectrally from a comparable
    non-dumpsite pixel AT ALL, and if so, is the difference at the
    C-H absorption features or somewhere else?

"Somewhere else" would mean we are looking at bare ground again, by a fourth
route, and Path B closes with the others.

WHAT THIS SCRIPT DOES, AND DOES NOT
-----------------------------------
It extracts spectra. It does not decide anything - the analysis, statistics and
figures live in `plastic_characterisation_workflow.ipynb` so the reasoning is
visible and revisable, matching how `dumpsite_detection_workflow.ipynb` and
`plasticwaste_analysis.ipynb` are organised.

MATCHED CONTROLS MATTER MORE THAN USUAL HERE
--------------------------------------------
Dumps sit at the settlement fringe. Negatives drawn from anywhere in Guinea are
mostly forest and farmland, so ANY comparison would "separate" - and would be
measuring settlement, exactly the confound that made a 250 m footprint look
like a dump detector in Module 1. Two control sets are therefore extracted:

  labelled_negative  the project's own 540 negative cells that fall in-scene
  ring_control       pixels drawn from an annulus 150-450 m around each dump,
                     i.e. the same neighbourhood, same illumination, same
                     acquisition, differing only in whether a dump is present

The ring control is the honest comparison. If dumps separate from labelled
negatives but NOT from their own surroundings, the signal is neighbourhood, not
waste.

Run:  python plasticwaste_tool/18_enmap_extract_spectra.py
Out:  plasticwaste_tool/runs/enmap_spectra/spectra.npz  (+ points.csv)
"""
