from __future__ import annotations

import glob
import json
import re
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
import pandas as pd

import sys
from ..geo_env import fix_proj  # noqa: E402

fix_proj()  # system PROJ_LIB points at PostGIS and breaks rasterio — see geo_env

HERE = Path(__file__).resolve().parent
# One level deeper than the numbered original: `runs/`,
# `manual_qa/` and the frozen models all live in the parent
# package directory, so paths climb one extra level.
TOOL = HERE.parent
SCENE_GLOB = str(TOOL / "runs" / "enmap_scenes" / "*")
LABELS_PATH = TOOL / "manual_qa" / "regions" / "national_random_sample.geojson"
OUT_DIR = TOOL / "runs" / "enmap_spectra"

# EnMAP L2A reflectance is stored as int16 scaled by 1e4.
REFL_SCALE = 1e-4
NODATA_SENTINELS = (-32768, -32767, 0)

RING_INNER_M, RING_OUTER_M = 150.0, 450.0
RING_PER_DUMP = 8
RNG_SEED = 0


def read_wavelengths(meta_path: Path) -> np.ndarray:
    xml = meta_path.read_text(encoding="utf-8", errors="ignore")
    vals = re.findall(r"<wavelengthCenterOfBand>([^<]+)</wavelengthCenterOfBand>", xml)
    return np.array([float(v) for v in vals], dtype=float)


def load_label_points() -> pd.DataFrame:
    with open(LABELS_PATH, "r", encoding="utf-8") as fh:
        gj = json.load(fh)
    rows = []
    for feat in gj["features"]:
        p = feat["properties"]
        tid, lab = str(p["tile_id"]), str(p.get("label"))
        if lab == "1" and p.get("lat"):
            lats = [s.strip() for s in str(p["lat"]).split(";") if s.strip()]
            lons = [s.strip() for s in str(p["long"]).split(";") if s.strip()]
            for i, (la, lo) in enumerate(zip(lats, lons)):
                rows.append({"point_id": f"{tid}_p{i}", "tile_id": tid,
                             "region": p.get("region"), "kind": "dump",
                             "lon": float(lo), "lat": float(la)})
        elif lab == "0":
            c = feat["geometry"]["coordinates"][0]
            rows.append({"point_id": tid, "tile_id": tid,
                         "region": p.get("region"), "kind": "labelled_negative",
                         "lon": float(np.mean([x[0] for x in c])),
                         "lat": float(np.mean([x[1] for x in c]))})
    return pd.DataFrame(rows)


def main() -> int:
    import rasterio
    from rasterio.warp import transform as warp_transform

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    scenes = [Path(p) for p in glob.glob(SCENE_GLOB) if Path(p).is_dir()]
    if not scenes:
        print("No EnMAP scene found — run 15_enmap_download.py first.")
        return 1

    all_rows: List[Dict] = []
    all_spec: List[np.ndarray] = []
    wavelengths = None

    for scene in scenes:
        cube = scene / "image.TIF"
        meta = scene / "metadata.XML"
        if not cube.exists() or not meta.exists():
            print(f"  skip {scene.name}: missing image.TIF or metadata.XML")
            continue

        wl = read_wavelengths(meta)
        print(f"\n{scene.name[:58]}")
        print(f"  {len(wl)} bands, {wl.min():.0f}-{wl.max():.0f} nm")
        if wavelengths is None:
            wavelengths = wl

        pts = load_label_points()
        with rasterio.open(cube) as src:
            if src.count != len(wl):
                print(f"  ! band/wavelength mismatch: {src.count} vs {len(wl)}")
                continue

            # Project lon/lat into the scene CRS, keep what falls inside.
            xs, ys = warp_transform("EPSG:4326", src.crs,
                                    pts["lon"].tolist(), pts["lat"].tolist())
            pts = pts.assign(x=xs, y=ys)
            l, b, r, t = src.bounds
            inside = pts[(pts.x >= l) & (pts.x <= r) & (pts.y >= b) & (pts.y <= t)].copy()
            n_dump = int((inside.kind == "dump").sum())
            print(f"  in-scene: {len(inside)} points "
                  f"({n_dump} dump, {len(inside) - n_dump} labelled negative)")
            if n_dump == 0:
                continue

            # Ring controls: same neighbourhood as each dump, no dump present.
            rng = np.random.default_rng(RNG_SEED)
            ring_rows = []
            for d in inside[inside.kind == "dump"].itertuples():
                ang = rng.uniform(0, 2 * np.pi, RING_PER_DUMP)
                rad = np.sqrt(rng.uniform(RING_INNER_M ** 2, RING_OUTER_M ** 2,
                                          RING_PER_DUMP))
                for k, (a, rr) in enumerate(zip(ang, rad)):
                    ring_rows.append({"point_id": f"{d.point_id}_ring{k}",
                                      "tile_id": d.tile_id, "region": d.region,
                                      "kind": "ring_control",
                                      "lon": np.nan, "lat": np.nan,
                                      "x": d.x + rr * np.cos(a),
                                      "y": d.y + rr * np.sin(a)})
            ring = pd.DataFrame(ring_rows)
            ring = ring[(ring.x >= l) & (ring.x <= r) & (ring.y >= b) & (ring.y <= t)]
            print(f"  ring controls in-scene: {len(ring)}")

            sample_pts = pd.concat([inside, ring], ignore_index=True)

            # Read the full cube once — 224 x 1324 x 1171 int16 is ~700 MB as
            # float32, so read as-is and convert per sample instead.
            arr = src.read()                       # (bands, rows, cols)

            # src.index() takes scalars only in this rasterio version. Apply the
            # inverse affine ourselves so the whole point set converts at once.
            inv = ~src.transform
            xv = sample_pts.x.to_numpy(dtype=float)
            yv = sample_pts.y.to_numpy(dtype=float)
            cols_idx = np.floor(inv.a * xv + inv.b * yv + inv.c).astype(int)
            rows_idx = np.floor(inv.d * xv + inv.e * yv + inv.f).astype(int)

            ok = ((rows_idx >= 0) & (rows_idx < src.height) &
                  (cols_idx >= 0) & (cols_idx < src.width))
            sample_pts = sample_pts[ok].copy()
            spec = arr[:, rows_idx[ok], cols_idx[ok]].T.astype(np.float32)

            valid = ~np.isin(spec, NODATA_SENTINELS).all(axis=1)
            spec, sample_pts = spec[valid], sample_pts[valid].copy()
            spec = spec * REFL_SCALE

            # A plausible surface reflectance spectrum: mostly in [0, 1].
            plausible = ((spec > -0.05) & (spec < 1.5)).mean(axis=1) > 0.9
            spec, sample_pts = spec[plausible], sample_pts[plausible].copy()

            # Write lon/lat back for every sampled point (ring controls were
            # generated in scene CRS and had none). Downstream consumers then
            # never need to know the scene's UTM zone — hardcoding it once
            # already put a map 6 degrees east of Conakry.
            lons, lats = warp_transform(src.crs, "EPSG:4326",
                                        sample_pts.x.tolist(), sample_pts.y.tolist())
            sample_pts["lon"] = lons
            sample_pts["lat"] = lats
            sample_pts["epsg"] = src.crs.to_epsg()
            sample_pts["scene"] = scene.name
            print(f"  usable spectra: {len(spec)}  "
                  f"({(sample_pts.kind == 'dump').sum()} dump, "
                  f"{(sample_pts.kind == 'labelled_negative').sum()} neg, "
                  f"{(sample_pts.kind == 'ring_control').sum()} ring)")

            all_rows.append(sample_pts)
            all_spec.append(spec)

    if not all_spec:
        print("\nNo spectra extracted.")
        return 1

    pts_out = pd.concat(all_rows, ignore_index=True)
    spec_out = np.vstack(all_spec)

    np.savez_compressed(OUT_DIR / "spectra.npz",
                        spectra=spec_out, wavelengths=wavelengths,
                        kind=pts_out["kind"].to_numpy().astype(str),
                        point_id=pts_out["point_id"].to_numpy().astype(str),
                        tile_id=pts_out["tile_id"].to_numpy().astype(str))
    pts_out.to_csv(OUT_DIR / "points.csv", index=False)

    print(f"\nWrote {spec_out.shape[0]} spectra x {spec_out.shape[1]} bands")
    print(f"  -> {OUT_DIR / 'spectra.npz'}")
    print(f"\nBy class:")
    for k, n in pts_out["kind"].value_counts().items():
        print(f"  {k:<20} {n}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
