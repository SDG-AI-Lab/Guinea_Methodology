def spatial_cv_model(df: pd.DataFrame, footprint: str) -> Dict:
    """
    Leave-one-region-out logistic regression over all indices.

    A single index is a fixed function and needs no CV. A fitted combination
    does, and it must be spatially blocked: a random split would put points
    from the same town in both train and test, which shares background,
    acquisition date and sensor geometry and inflates the score.
    """
    from sklearn.linear_model import LogisticRegression
    from sklearn.pipeline import make_pipeline
    from sklearn.preprocessing import StandardScaler
    from sklearn.impute import SimpleImputer

    sub = df[df["footprint"] == footprint].dropna(subset=["B11"]).copy()
    feats = [c for c in INDEX_COLUMNS if c in sub.columns]
    X_all = sub[feats].replace([np.inf, -np.inf], np.nan)
    y_all = sub["label"].to_numpy()
    regions = sub["region"].to_numpy()

    print(f"\n  Leave-one-region-out logistic regression ({len(feats)} indices):")
    rows = []
    oof = np.full(len(sub), np.nan)
    for reg in sorted(set(regions)):
        te = regions == reg
        tr = ~te
        if y_all[tr].sum() < 5 or y_all[te].sum() < 1:
            print(f"    {reg:<12} skipped (too few positives)")
            continue
        model = make_pipeline(SimpleImputer(strategy="median"),
                              StandardScaler(),
                              LogisticRegression(max_iter=2000, class_weight="balanced"))
        model.fit(X_all[tr], y_all[tr])
        p = model.predict_proba(X_all[te])[:, 1]
        oof[te] = p
        ap = average_precision_score(y_all[te], p)
        base = y_all[te].mean()
        rows.append({"region": reg, "n": int(te.sum()), "n_pos": int(y_all[te].sum()),
                     "ap": float(ap), "baseline": float(base)})
        print(f"    {reg:<12} n={te.sum():>4} pos={int(y_all[te].sum()):>3} "
              f"AP={ap:.3f}  baseline={base:.3f}")

    m = np.isfinite(oof)
    pooled = float(average_precision_score(y_all[m], oof[m])) if m.sum() else float("nan")
    print(f"    {'POOLED OOF':<12} AP={pooled:.3f}  "
          f"baseline={y_all[m].mean():.3f}")
    return {"per_region": rows, "pooled_oof_ap": pooled,
            "pooled_baseline": float(y_all[m].mean()) if m.sum() else None}


def incremental_value_test(df: pd.DataFrame, footprint: str) -> Dict:
    """
    THE decisive test: do the plastic indices add anything beyond "this pixel
    has no vegetation"?

    Every index above separates dumps from non-dumps, but so does NDVI, which
    has no plastic sensitivity at all. That is consistent with the indices
    detecting *bare ground* rather than *plastic*. This test settles it by
    comparing two spatially-blocked models on identical folds:

        NDVI only            vs    NDVI + every plastic index

    If the plastic indices carried plastic-specific information, the second
    model would beat the first. The comparison is a paired bootstrap on the
    out-of-fold predictions (Schenker & Gentleman 2001), not a comparison of
    two marginal confidence intervals.
    """
    from sklearn.linear_model import LogisticRegression
    from sklearn.pipeline import make_pipeline
    from sklearn.preprocessing import StandardScaler
    from sklearn.impute import SimpleImputer

    sub = df[df["footprint"] == footprint].dropna(subset=["B11"]).copy()
    y = sub["label"].to_numpy()
    regions = sub["region"].to_numpy()
    tiles = sub["tile_id"].to_numpy()

    plastic_only = [c for c in INDEX_COLUMNS
                    if c in sub.columns and c not in ("NDVI", "NDBI")]
    feature_sets = {
        "NDVI_only": ["NDVI"],
        "plastic_indices_only": plastic_only,
        "NDVI_plus_plastic": ["NDVI"] + plastic_only,
    }

    oof: Dict[str, np.ndarray] = {}
    for name, feats in feature_sets.items():
        X = sub[feats].replace([np.inf, -np.inf], np.nan)
        pred = np.full(len(sub), np.nan)
        for reg in sorted(set(regions)):
            te = regions == reg
            tr = ~te
            if y[tr].sum() < 5 or y[te].sum() < 1:
                continue
            m = make_pipeline(SimpleImputer(strategy="median"), StandardScaler(),
                              LogisticRegression(max_iter=2000, class_weight="balanced"))
            m.fit(X[tr], y[tr])
            pred[te] = m.predict_proba(X[te])[:, 1]
        oof[name] = pred

    valid = np.all([np.isfinite(v) for v in oof.values()], axis=0)
    y_v = y[valid]
    aps = {k: float(average_precision_score(y_v, v[valid])) for k, v in oof.items()}

    print(f"\n  Incremental value over NDVI (leave-one-region-out, "
          f"n={valid.sum()}, baseline={y_v.mean():.3f}):")
    for k, v in aps.items():
        print(f"    {k:<24} OOF AP = {v:.3f}")

    rng = np.random.default_rng(RNG_SEED)
    boot = cluster_boot_indices(tiles[valid], rng, N_BOOT)
    comparisons = {}
    for a, b in [("NDVI_plus_plastic", "NDVI_only"),
                 ("plastic_indices_only", "NDVI_only")]:
        diffs = []
        for idx in boot:
            yy = y_v[idx]
            if yy.sum() < 2 or yy.sum() == len(yy):
                continue
            diffs.append(average_precision_score(yy, oof[a][valid][idx])
                         - average_precision_score(yy, oof[b][valid][idx]))
        diffs = np.asarray(diffs)
        lo, hi = np.percentile(diffs, [2.5, 97.5])
        sig = bool(lo > 0 or hi < 0)
        comparisons[f"{a}_minus_{b}"] = {
            "delta_ap": float(diffs.mean()), "ci95": [float(lo), float(hi)],
            "excludes_zero": sig}
        print(f"    {a} - {b}: dAP={diffs.mean():+.3f} "
              f"[{lo:+.3f}, {hi:+.3f}]  "
              f"{'SIGNIFICANT' if sig else 'NOT SIGNIFICANT'}")

    return {"oof_ap": aps, "baseline": float(y_v.mean()),
            "paired_comparisons": comparisons}


def main() -> int:
    if not SAMPLES_CSV.exists():
        print(f"Missing {SAMPLES_CSV} — run 11_s2_plastic_indices.py first.")
        return 1

    df = pd.read_csv(SAMPLES_CSV)
    df = df.replace([np.inf, -np.inf], np.nan)
    print(f"Loaded {len(df)} rows, footprints: {sorted(df['footprint'].unique())}")

    out = {"n_boot": N_BOOT, "footprints": {}}
    for fp in sorted(df["footprint"].unique()):
        res = evaluate_footprint(df, fp)
        if res.get("status") == "ok":
            res["spatial_cv"] = spatial_cv_model(df, fp)
            res["incremental_value"] = incremental_value_test(df, fp)
        out["footprints"][fp] = res

    with open(RUN_DIR / "evaluation.json", "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=2)
    print(f"\nWritten to {RUN_DIR / 'evaluation.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
