TOOL = HERE.parent
RUN_DIR = TOOL / "runs" / "s2_plastic_indices"
SAMPLES_CSV = RUN_DIR / "s2_index_samples.csv"

INDEX_COLUMNS = ["NDVI", "NDBI", "PMLI", "PGI", "RPGI", "PGI_altdenom", "Vi",
                 "PMLI_NIR", "PMLI_SWIR", "PMLI_ND"]

N_BOOT = 2000
RNG_SEED = 0


