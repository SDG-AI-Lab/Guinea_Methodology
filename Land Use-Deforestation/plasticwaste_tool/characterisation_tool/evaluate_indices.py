def oriented_ap(y: np.ndarray, score: np.ndarray) -> Tuple[float, int]:
    """Average precision, trying both orientations. Returns (ap, sign)."""
    ap_pos = average_precision_score(y, score)
    ap_neg = average_precision_score(y, -score)
    return (ap_pos, 1) if ap_pos >= ap_neg else (ap_neg, -1)


def cluster_boot_indices(tiles: np.ndarray, rng: np.random.Generator,
                         n_boot: int) -> List[np.ndarray]:
    """
    Resample whole tiles with replacement, returning row indices per replicate.
    Keeps multiple dump points from one label cell together.
    """
    uniq = np.unique(tiles)
    by_tile = {t: np.flatnonzero(tiles == t) for t in uniq}
    out = []
    for _ in range(n_boot):
        drawn = rng.choice(uniq, size=len(uniq), replace=True)
        out.append(np.concatenate([by_tile[t] for t in drawn]))
    return out


def evaluate_footprint(df: pd.DataFrame, footprint: str) -> Dict:
    sub = df[df["footprint"] == footprint].copy()
    usable = sub.dropna(subset=["B11"])
    y = usable["label"].to_numpy()
    tiles = usable["tile_id"].to_numpy()
    prevalence = float(y.mean())

    print(f"\n{'=' * 74}\nFOOTPRINT: {footprint}\n{'=' * 74}")
    print(f"  usable points: {len(usable)}/{len(sub)}   "
          f"positives {int(y.sum())}   prevalence (AP baseline) {prevalence:.3f}")

    if y.sum() < 10 or len(usable) < 50:
        print("  ! too few usable points — skipping")
        return {"footprint": footprint, "status": "insufficient_data"}

    rng = np.random.default_rng(RNG_SEED)
    boot_idx = cluster_boot_indices(tiles, rng, N_BOOT)

    results = {}
    boot_ap: Dict[str, np.ndarray] = {}

    for col in INDEX_COLUMNS:
        if col not in usable.columns:
            continue
        s = usable[col].to_numpy(dtype=float)
        ok = np.isfinite(s)
        if ok.sum() < 50 or y[ok].sum() < 5:
            continue
        ap, sign = oriented_ap(y[ok], s[ok])

        reps = np.full(N_BOOT, np.nan)
        for i, idx in enumerate(boot_idx):
            yy, ss = y[idx], s[idx]
            m = np.isfinite(ss)
            if m.sum() < 20 or yy[m].sum() < 2 or yy[m].sum() == m.sum():
                continue
            reps[i] = average_precision_score(yy[m], sign * ss[m])
        boot_ap[col] = reps

        lo, hi = np.nanpercentile(reps, [2.5, 97.5])
        lift = ap / prevalence
        results[col] = {"ap": float(ap), "sign": int(sign),
                        "ci95": [float(lo), float(hi)],
                        "lift_over_baseline": float(lift)}

    # Ranked table
    order = sorted(results, key=lambda c: -results[c]["ap"])
    print(f"\n  {'index':<14}{'AP':>7}{'95% CI':>18}{'lift':>7}  dir")
    print(f"  {'-' * 52}")
    print(f"  {'(baseline)':<14}{prevalence:>7.3f}{'':>18}{1.0:>7.2f}")
    for c in order:
        r = results[c]
        ci = f"[{r['ci95'][0]:.3f}, {r['ci95'][1]:.3f}]"
        print(f"  {c:<14}{r['ap']:>7.3f}{ci:>18}{r['lift_over_baseline']:>7.2f}"
              f"  {'+' if r['sign'] > 0 else '-'}")

    # Paired bootstrap: best index vs NDVI control, and vs baseline
    comparisons = {}
    if order:
        best = order[0]
        for other in order[1:]:
            d = boot_ap[best] - boot_ap[other]
            d = d[np.isfinite(d)]
            if d.size < 100:
                continue
            lo, hi = np.percentile(d, [2.5, 97.5])
            comparisons[f"{best}_minus_{other}"] = {
                "delta_ap": float(np.mean(d)), "ci95": [float(lo), float(hi)],
                "excludes_zero": bool(lo > 0 or hi < 0)}

        # Is the best index even above the no-skill baseline?
        d0 = boot_ap[best] - prevalence
        d0 = d0[np.isfinite(d0)]
        lo, hi = np.percentile(d0, [2.5, 97.5])
        comparisons[f"{best}_minus_baseline"] = {
            "delta_ap": float(np.mean(d0)), "ci95": [float(lo), float(hi)],
            "excludes_zero": bool(lo > 0)}

        print(f"\n  Paired bootstrap (best = {best}):")
        for k, v in comparisons.items():
            flag = "SIGNIFICANT" if v["excludes_zero"] else "not significant"
            print(f"    {k:<34} dAP={v['delta_ap']:+.3f} "
                  f"[{v['ci95'][0]:+.3f}, {v['ci95'][1]:+.3f}]  {flag}")

    return {"footprint": footprint, "status": "ok", "n_points": int(len(usable)),
            "n_positive": int(y.sum()), "prevalence": prevalence,
            "indices": results, "paired_comparisons": comparisons}


