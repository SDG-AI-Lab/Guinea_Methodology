"""
12 — Evaluate whether Sentinel-2 plastic indices separate dumps from non-dumps.

Reads `runs/s2_plastic_indices/s2_index_samples.csv` (written by script 11) and
answers one question: **do any of these indices carry signal about dumpsites?**

This is the decision gate for Path A. If the answer is no, the plastic-mulch
index family does not rank plastic content within dumps either, and the
approach should be dropped rather than tuned.

STATISTICAL CHOICES, AND WHY
----------------------------

* **Average precision, not ROC-AUC.** The sample is 111 positives against 540
  negatives (17% prevalence), and under class imbalance ROC-AUC is optimistic
  and hard to interpret — a large number of false positives barely moves it
  because the negative class is big. Precision-recall is the informative view
  (Saito & Rehmsmeier 2015, PLoS ONE 10:e0118432). The no-skill baseline for
  AP is the positive prevalence, not 0.5.

* **Cluster bootstrap, not a naive one.** A single 250 m label cell can
  contribute several dump points, so points are not independent. Bootstrap
  replicates resample whole *tiles*, keeping within-tile points together.

* **Paired bootstrap for every comparison.** Comparing two indices by checking
  whether their marginal confidence intervals overlap is a known error — two
  overlapping CIs can still correspond to a highly significant difference
  (Schenker & Gentleman 2001, Am. Stat. 55:182-186). So differences are
  computed *within* each bootstrap replicate and the CI is formed on the
  difference itself.

* **Leave-one-region-out spatial CV for anything fitted.** A raw index needs no
  training, so its AP can be computed directly on all points. The moment
  indices get combined into a fitted model, spatially independent evaluation
  is required, because nearby sites share background, season and sensor
  geometry and a random split would leak that (Roberts et al. 2017, Ecography
  40:913-929). Guinea's eight administrative regions are used as blocks.

* **Index orientation is selected, and that is declared.** An index might
  separate in either direction, so both the index and its negation are scored
  and the better is reported. That is a 2-way selection on the same data and
  mildly inflates AP; it is stated rather than hidden, and it only matters if
  a result is near the baseline — which, for a falsification test, is exactly
  the regime where a false positive would be costly.

Run:  python plasticwaste_tool/12_evaluate_s2_indices.py
"""
