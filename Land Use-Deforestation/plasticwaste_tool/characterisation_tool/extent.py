LABELS_PATH = TOOL / "manual_qa" / "regions" / "national_random_sample.geojson"
OUT_DIR = TOOL / "runs" / "dumpsite_extent"

TILE_M = 80.0          # from manual_qa/_metrics_pt80_google.json
IMG_PX = 800
M_PER_PX = TILE_M / IMG_PX          # 0.1 m/px
ATTRIB_BAR_PX = 70                  # Google attribution strip at the bottom
MAX_RADIUS_PX = 330                 # 33 m — stays clear of the frame and the bar
ANNULUS_STEP_PX = 10                # 1 m rings
BASELINE_RING_PX = (300, 330)       # 30–33 m, treated as local background


def _load_gray(path: Path) -> Optional[np.ndarray]:
    try:
        im = Image.open(path).convert("L")
    except Exception:
        return None
    a = np.asarray(im, dtype=np.float32) / 255.0
    if a.shape != (IMG_PX, IMG_PX):
        im = im.resize((IMG_PX, IMG_PX))
        a = np.asarray(im, dtype=np.float32) / 255.0
    return a


def _local_texture(gray: np.ndarray, k: int = 5) -> np.ndarray:
    """Local standard deviation in a k x k window — waste is texturally busy."""
    from scipy.ndimage import uniform_filter
    mean = uniform_filter(gray, size=k, mode="reflect")
    mean_sq = uniform_filter(gray ** 2, size=k, mode="reflect")
    return np.sqrt(np.maximum(mean_sq - mean ** 2, 0.0))


def radial_profile(gray: np.ndarray) -> Dict[str, np.ndarray]:
    """Mean brightness and texture in 1 m annuli around the crop centre."""
    tex = _local_texture(gray)
    h, w = gray.shape
    yy, xx = np.mgrid[0:h, 0:w]
    cy = cx = IMG_PX / 2.0
    r = np.hypot(yy - cy, xx - cx)

    valid = np.ones_like(gray, dtype=bool)
    valid[h - ATTRIB_BAR_PX:, :] = False       # drop the attribution strip

    edges = np.arange(0, MAX_RADIUS_PX + 1, ANNULUS_STEP_PX)
    bright, texture, radii = [], [], []
    for i in range(len(edges) - 1):
        m = (r >= edges[i]) & (r < edges[i + 1]) & valid
        if m.sum() < 20:
            continue
        bright.append(float(gray[m].mean()))
        texture.append(float(tex[m].mean()))
        radii.append((edges[i] + edges[i + 1]) / 2.0 * M_PER_PX)
    return {"radius_m": np.array(radii), "brightness": np.array(bright),
            "texture": np.array(texture)}


def disturbance_radius(prof: Dict[str, np.ndarray]) -> Dict[str, float]:
    """
    Half-maximum decay radius: where the centre's excess over background has
    fallen to half.

    An earlier version used "last radius outside a +-1 sigma background band".
    That was discarded because it FAILED its own control — dumps and non-dumps
    both returned ~32 m with about half the sample censored at the frame edge,
    i.e. it measured generic scene structure, not the dump. The failure is kept
    in the record rather than tuned away.

    Half-maximum is robust because it is referenced to the site's own centre
    excess rather than to a noisy background band. It is only meaningful where
    a centre excess actually exists, so `*_excess_sigma` is reported alongside
    and the radius should be read as undefined where that excess is small.
    """
    out: Dict[str, float] = {}
    r = prof["radius_m"]
    for key in ("brightness", "texture"):
        v = prof[key]
        if v.size < 8:
            out[f"{key}_radius_m"] = float("nan")
            out[f"{key}_excess_sigma"] = float("nan")
            continue
        outer = v[int(len(v) * 0.66):]
        base, sigma = float(np.median(outer)), float(np.std(outer)) + 1e-6
        centre = float(np.mean(v[:2]))
        excess = centre - base
        out[f"{key}_excess_sigma"] = float(excess / sigma)

        if abs(excess) < 1e-6:
            out[f"{key}_radius_m"] = float("nan")
            continue
        half = base + excess / 2.0
        # first radius at which the profile has crossed the half-way level
        below = ((v <= half) if excess > 0 else (v >= half))
        idx = np.flatnonzero(below)
        out[f"{key}_radius_m"] = float(r[idx[0]]) if idx.size else float("nan")

        # Encircled-excess radii. Half-maximum tracks the sharp central core
        # and under-reads a diffuse scatter; integrating the excess weighted by
        # annulus area is the standard way to size a diffuse source and is what
        # a pixel-count argument actually needs.
        exc = np.clip(v - base, 0, None) if excess > 0 else np.clip(base - v, 0, None)
        weight = exc * r                      # annulus area goes as r
        total = weight.sum()
        if total <= 0:
            out[f"{key}_r50_m"] = float("nan")
            out[f"{key}_r90_m"] = float("nan")
            continue
        cum = np.cumsum(weight) / total
        for frac, name in ((0.5, "r50"), (0.9, "r90")):
            j = np.flatnonzero(cum >= frac)
            out[f"{key}_{name}_m"] = float(r[j[0]]) if j.size else float("nan")
    return out


def load_point_index() -> pd.DataFrame:
    with open(LABELS_PATH, "r", encoding="utf-8") as fh:
        gj = json.load(fh)
    rows = []
    for f in gj["features"]:
        p = f["properties"]
        tid, lab = str(p["tile_id"]), str(p.get("label"))
        if lab == "1" and p.get("lat"):
            n = len([s for s in str(p["lat"]).split(";") if s.strip()])
            for i in range(n):
                rows.append({"point_id": f"{tid}_p{i}", "tile_id": tid,
                             "region": p.get("region"), "label": 1,
                             "confidence": p.get("confidence")})
        elif lab == "0":
            rows.append({"point_id": tid, "tile_id": tid,
                         "region": p.get("region"), "label": 0,
                         "confidence": p.get("confidence")})
    return pd.DataFrame(rows)


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    print("=" * 74)
    print("Dumpsite extent from 80 m / 0.1 m-per-pixel crops")
    print("=" * 74)

    idx = load_point_index()
    print(f"\nLabelled points: {len(idx)} "
          f"({(idx.label == 1).sum()} positive, {(idx.label == 0).sum()} negative)")

    recs: List[Dict] = []
    missing = 0
    for row in idx.itertuples():
        path = CROP_DIR / f"{row.point_id}.png"
        if not path.exists():
            path = CROP_DIR_ESRI / f"{row.point_id}.png"
        if not path.exists():
            missing += 1
            continue
        gray = _load_gray(path)
        if gray is None:
            missing += 1
            continue
        prof = radial_profile(gray)
        rec = {"point_id": row.point_id, "tile_id": row.tile_id,
               "region": row.region, "label": row.label,
               "confidence": row.confidence}
        rec.update(disturbance_radius(prof))
        recs.append(rec)

    df = pd.DataFrame(recs)
    df.to_csv(OUT_DIR / "extent_measurements.csv", index=False)
    print(f"Measured {len(df)} crops ({missing} missing)")

    summary = {"tile_m": TILE_M, "m_per_px": M_PER_PX,
               "max_measurable_radius_m": MAX_RADIUS_PX * M_PER_PX,
               "n_measured": int(len(df)), "n_missing": int(missing)}

    print(f"\n{'-' * 74}")
    print("Disturbance radius (m) — dumps vs non-dumps")
    print(f"{'-' * 74}")
    print(f"  {'metric':<22}{'class':<12}{'n':>5}{'p25':>7}{'median':>8}{'p75':>7}"
          f"{'p90':>7}{'censored':>10}")
    for metric in ("brightness_radius_m", "texture_radius_m",
                   "brightness_r50_m", "texture_r50_m",
                   "brightness_r90_m", "texture_r90_m"):
        for lab, name in ((1, "dump"), (0, "non-dump")):
            v = df[df.label == lab][metric].dropna()
            if v.empty:
                continue
            cens = float((v >= MAX_RADIUS_PX * M_PER_PX - 0.6).mean())
            label = metric[:-2]
            print(f"  {label:<22}{name:<12}{len(v):>5}"
                  f"{v.quantile(.25):>7.1f}{v.median():>8.1f}{v.quantile(.75):>7.1f}"
                  f"{v.quantile(.90):>7.1f}{cens:>9.0%}")
            summary.setdefault(metric, {})[name] = {
                "n": int(len(v)), "p25": float(v.quantile(.25)),
                "median": float(v.median()), "p75": float(v.quantile(.75)),
                "p90": float(v.quantile(.90)), "censored_fraction": cens}

    # Falsification: does the measure distinguish dumps from non-dumps at all?
    print(f"\n{'-' * 74}")
    print("Does the measure separate dumps from non-dumps? (centre excess, sigma)")
    print(f"{'-' * 74}")
    for metric in ("brightness_excess_sigma", "texture_excess_sigma"):
        d = df[df.label == 1][metric].dropna()
        n = df[df.label == 0][metric].dropna()
        if d.empty or n.empty:
            continue
        print(f"  {metric:<38} dumps median {d.median():+.2f}   "
              f"non-dumps median {n.median():+.2f}")
        summary.setdefault("centre_excess", {})[metric] = {
            "dump_median": float(d.median()), "nondump_median": float(n.median())}

    # --- Gate: does ANY radius estimator pass its own control? --------------
    #
    # Criteria fixed before looking at the numbers: a usable estimator must
    # (a) give dumps a LARGER radius than non-dumps by a clear margin, and
    # (b) not be mostly censored at the frame edge. A number that fails these
    # is not a measurement, and the script must not print pixel counts derived
    # from it -- that is exactly how an unsupported figure ends up in a
    # methodology document.
    print(f"\n{'-' * 74}")
    print("Estimator control check (dump radius must exceed non-dump radius)")
    print(f"{'-' * 74}")
    usable = []
    for metric in ("texture_radius_m", "brightness_radius_m",
                   "texture_r50_m", "brightness_r50_m",
                   "texture_r90_m", "brightness_r90_m"):
        d = df[df.label == 1][metric].dropna()
        n = df[df.label == 0][metric].dropna()
        if d.empty or n.empty:
            continue
        ratio = d.median() / n.median() if n.median() else float("nan")
        cens = float((d >= MAX_RADIUS_PX * M_PER_PX - 0.6).mean())
        ok = ratio >= 1.25 and cens < 0.25
        print(f"  {metric[:-2]:<22} dump/non-dump median ratio {ratio:>5.2f}   "
              f"censored {cens:>4.0%}   {'PASS' if ok else 'FAIL'}")
        summary.setdefault("estimator_control", {})[metric] = {
            "dump_median": float(d.median()), "nondump_median": float(n.median()),
            "ratio": float(ratio), "censored": cens, "passes": bool(ok)}
        if ok:
            usable.append(metric)

    print(f"\n{'-' * 74}")
    if not usable:
        print("EXTENT NOT MEASURABLE from these crops")
        print(f"{'-' * 74}")
        print("  No radius estimator passed its control, so no pixel-count")
        print("  figure is emitted. What IS established:")
        print(f"    texture centre excess  dumps {df[df.label == 1]['texture_excess_sigma'].median():+.2f}"
              f" sigma vs non-dumps {df[df.label == 0]['texture_excess_sigma'].median():+.2f} sigma")
        print("  i.e. something radiometrically distinctive sits at the labelled")
        print("  point, but how far it extends is not recoverable this way.")
        print("  Manual annotation of a subsample is the way to get extents.")
        summary["extent_measurable"] = False
        summary["pixels"] = None
    else:
        metric = usable[0]
        med = float(df[df.label == 1][metric].median())
        diam = 2 * med
        print(f"CORE size only — LOWER BOUND on extent (via {metric[:-2]})")
        print(f"{'-' * 74}")
        print(f"  median half-maximum radius {med:.1f} m -> ~{diam:.0f} m core")
        for name, gsd in (("Sentinel-2 SWIR", 20), ("EnMAP", 30), ("EMIT", 60)):
            print(f"    {name:<18} {gsd:>3} m   {diam ** 2 / gsd ** 2:>6.2f} px")
        print()
        print("  READ THIS AS A LOWER BOUND, NOT AN EXTENT. Half-maximum tracks")
        print("  the sharp radiometric core of the site. The encircled-excess")
        print("  estimators, which would have captured the diffuse outer")
        print("  extent, all FAILED their control above (non-dumps scored")
        print("  LARGER than dumps, because with no central peak their 'excess'")
        print("  is just background noise spread over the whole frame).")
        print("  So: the core is sub-pixel at every sensor. The full extent is")
        print("  bounded below by this and not bounded above by this method.")
        summary["extent_measurable"] = "core_only_lower_bound"
        summary["estimator_used"] = metric
        summary["median_core_radius_m"] = med
        summary["implied_core_diameter_m"] = diam
        summary["core_pixels"] = {n: float(diam ** 2 / g ** 2)
                                  for n, g in (("Sentinel-2 SWIR", 20), ("EnMAP", 30), ("EMIT", 60))}

    summary["excess_sigma"] = {
        "texture_dump_median": float(df[df.label == 1]["texture_excess_sigma"].median()),
        "texture_nondump_median": float(df[df.label == 0]["texture_excess_sigma"].median()),
        "brightness_dump_median": float(df[df.label == 1]["brightness_excess_sigma"].median()),
        "brightness_nondump_median": float(df[df.label == 0]["brightness_excess_sigma"].median()),
    }

    with open(OUT_DIR / "extent_summary.json", "w", encoding="utf-8") as fh:
        json.dump(summary, fh, indent=2)
    print(f"\nWritten to {OUT_DIR}")
    return 0


