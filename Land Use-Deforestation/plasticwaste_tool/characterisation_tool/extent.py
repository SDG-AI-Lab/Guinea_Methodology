"""
14 — How large is a Guinean dumpsite, in metres?

WHY THIS NUMBER IS NEEDED
-------------------------
`docs/DPWMS_Hyperspectral_Coverage_Findings.md` §5 computes how many pixels a
dumpsite occupies at each sensor's resolution — and rests the whole calculation
on an **assumed** 50 m site, because Guinea dumpsite extents have never been
digitised. The labels are 250 m cells plus a point coordinate, not polygons.

That assumed number is what decides whether hyperspectral is worth pursuing:

    Sentinel-2 SWIR  20 m    50 m site -> 6.25 px
    EnMAP            30 m    50 m site -> 2.78 px
    EMIT             60 m    50 m site -> 0.69 px   (sub-pixel)

If real sites are nearer 20 m, EnMAP is sub-pixel too and the hyperspectral
path is spatially hopeless regardless of its spectral advantage. So this is
measured before anything further is committed.

WHAT IS MEASURED, AND WHAT IS NOT
---------------------------------
Segmenting "waste" from RGB is the unsolved problem at the heart of this whole
module — if it were solvable, characterisation would already be done. So this
script does NOT attempt to classify waste pixels and then measure them. That
would produce an extent number whose errors are the very thing under study.

Instead it measures a well-defined, unsupervised quantity: concentric annuli
are taken around the labelled point in the 0.1 m/px crop, and brightness and
local texture are profiled outwards. Two numbers come out:

  *_excess_sigma  how far the CENTRE stands above the crop's own background,
                  in robust sigmas — i.e. is there anything distinctive here
  *_radius_m      the half-maximum decay radius: where that excess has fallen
                  by half — i.e. how far the distinctive thing extends

This is a *characteristic scale of local disturbance*, not a waste polygon. It
is the right input for a pixel-count argument and the wrong input for an area
statistic, and it is reported as such. The radius is only interpretable where
the excess is real, so the two must be read together.

THE BUILT-IN FALSIFICATION
--------------------------
The same measurement is run on the 540 NEGATIVE points. If non-dumps return the
same radii as dumps, the measure is picking up generic scene structure and means
nothing. The dump/non-dump contrast is the check that it measures anything at
all — reported alongside the result rather than assumed.

TWO CENSORING LIMITS, BOTH REAL
-------------------------------
* The crops are 80 m across, so any site larger than ~35 m radius is
  **right-censored** — it reads as "at least this big" and no more.
* Google's attribution bar occupies the bottom ~70 px of every crop and is
  excluded; annuli are capped well inside the frame.

Run:  python plasticwaste_tool/14_dumpsite_extent.py
Out:  plasticwaste_tool/runs/dumpsite_extent/extent_measurements.csv
      plasticwaste_tool/runs/dumpsite_extent/extent_summary.json
"""
