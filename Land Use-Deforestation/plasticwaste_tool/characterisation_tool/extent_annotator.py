"""
16 — Build a local HTML tool for annotating dumpsite extents.

WHY THIS EXISTS
---------------
`14_dumpsite_extent.py` tried to measure dumpsite extent automatically from the
80 m crops and failed its own control: every radius estimator either saturated
at the frame edge, measured only the bright core, or ran backwards (non-dumps
scoring larger than dumps). The honest outcome was a lower bound — a ~7 m core —
and no upper bound at all.

Extent is the number the whole Path B decision turns on. `hyperspectral
coverage findings` §5 currently assumes 50 m per site, and that assumption
decides whether EnMAP's 30 m pixel can resolve anything:

    50 m site -> 2.78 EnMAP px        20 m site -> 0.44 EnMAP px

So it has to be measured by a person. This generates the tool for that.

DESIGN DECISIONS
----------------
* **Per cell, not per point.** Extent is a property of a site. Annotating every
  point would over-weight cells that happen to carry many (nat_kank_0018 alone
  has 12), which is exactly the clustering that distorts point-level counts.

* **Region-interleaved order.** Sites are ordered so that stopping early still
  leaves a regionally balanced sample. Annotate 30 and quit and the sample is
  still spread across Guinea; annotate all 55 and nothing is wasted.

* **Censoring is recorded, not hidden.** The 80 m crop cannot show a site
  larger than 80 m. Rather than silently truncating, there is an explicit
  "extends beyond frame" flag, so the resulting distribution can be treated as
  right-censored instead of quietly wrong.

* **A "not a dump" flag.** `nat_kank_0018` appears to be artisanal mining
  sheeting on a river sandbar rather than waste, and 54 of 55 positive cells
  are labelled low or medium confidence. The tool lets the annotator correct
  the label while they are already looking at the imagery — that is nearly free
  and the label set needs it.

* **Two views side by side.** The 80 m point-centred crop (0.1 m/px) for
  detail, and the 250 m cell crop (0.31 m/px) for context, so the annotator can
  see whether the site continues past the detail frame.

Run:  python plasticwaste_tool/16_build_extent_annotator.py
Then: open plasticwaste_tool/manual_qa/annotate_extent.html in a browser
Out:  the browser downloads extent_annotations.csv when you click Export
      -> feed it to 17_ingest_extent_annotations.py
"""
