def build_site_list() -> List[Dict]:
    with open(LABELS_PATH, "r", encoding="utf-8") as fh:
        gj = json.load(fh)

    by_region: Dict[str, List[Dict]] = defaultdict(list)
    for feat in gj["features"]:
        p = feat["properties"]
        if str(p.get("label")) != "1" or not p.get("lat"):
            continue
        tid = str(p["tile_id"])
        lats = [s.strip() for s in str(p["lat"]).split(";") if s.strip()]
        lons = [s.strip() for s in str(p["long"]).split(";") if s.strip()]
        if not lats:
            continue
        detail = QA_DIR / DETAIL_DIR / f"{tid}_p0.png"
        if not detail.exists():
            continue
        context = QA_DIR / CONTEXT_DIR / f"{tid}.png"
        by_region[str(p.get("region"))].append({
            "point_id": f"{tid}_p0",
            "tile_id": tid,
            "region": str(p.get("region")),
            "confidence": str(p.get("confidence")),
            "notes": str(p.get("notes") or ""),
            "n_points_in_cell": len(lats),
            "lat": float(lats[0]),
            "lon": float(lons[0]),
            "detail": f"{DETAIL_DIR}/{tid}_p0.png",
            "context": f"{CONTEXT_DIR}/{tid}.png" if context.exists() else "",
        })

    # Interleave regions, largest group first, so an early stop stays balanced.
    order = sorted(by_region, key=lambda r: -len(by_region[r]))
    out: List[Dict] = []
    i = 0
    while any(by_region[r][i:] for r in order):
        for r in order:
            if i < len(by_region[r]):
                out.append(by_region[r][i])
        i += 1
    return out


