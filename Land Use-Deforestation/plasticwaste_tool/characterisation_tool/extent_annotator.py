def main() -> int:
    sites = build_site_list()
    if not sites:
        print("No positive sites with crops found.")
        return 1

    html = (HTML
            .replace("__SITES__", json.dumps(sites))
            .replace("__DETAIL_M__", str(DETAIL_M)))
    OUT_HTML.write_text(html, encoding="utf-8")

    print(f"Wrote {OUT_HTML}")
    print(f"  {len(sites)} positive sites, region-interleaved")
    from collections import Counter
    print(f"  first 30 cover: {dict(Counter(s['region'] for s in sites[:30]))}")
    print(f"  all {len(sites)} cover: {dict(Counter(s['region'] for s in sites))}")
    print("\nOpen it in a browser, drag across the widest part of each dump,")
    print("then click Export CSV and save next to this script's output dir.")
    return 0


