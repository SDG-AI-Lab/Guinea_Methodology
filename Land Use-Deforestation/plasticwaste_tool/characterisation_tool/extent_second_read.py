import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
# One level deeper than the numbered original: `runs/`,
# `manual_qa/` and the frozen models all live in the parent
# package directory, so paths climb one extra level.
TOOL = HERE.parent
QA = TOOL / "manual_qa"
CROPS = QA / "tiles_pt80_google"
RUN = TOOL / "runs" / "dumpsite_extent"
REVIEW = RUN / "second_read_crops"

FIRST = RUN / "extent_annotated_usable.csv"
SAMPLE = RUN / "second_read_sample.csv"
SECOND = RUN / "second_read.csv"

TILE_M = 80.0
IMG_PX = 800
SEED = 7


def render(point_id: str, dest: Path) -> bool:
    """
    Redraw the crop with a metric grid so the second read is measured, not
    guessed. Same 10/20/30 m reference rings the first-pass tool showed, plus a
    10 m grid and a scale bar. The Google attribution strip is left visible so
    it is obvious it has not been cropped away.
    """
    from PIL import Image, ImageDraw

    src = CROPS / f"{point_id}.png"
    if not src.exists():
        return False
    im = Image.open(src).convert("RGB")
    if im.size != (IMG_PX, IMG_PX):
        im = im.resize((IMG_PX, IMG_PX))
    d = ImageDraw.Draw(im, "RGBA")
    ppm = IMG_PX / TILE_M           # pixels per metre = 10
    c = IMG_PX / 2

    for m in range(10, 41, 10):     # 10 m grid
        for sign in (1, -1):
            off = c + sign * m * ppm
            if 0 <= off <= IMG_PX:
                d.line([(off, 0), (off, IMG_PX)], fill=(255, 255, 255, 55), width=1)
                d.line([(0, off), (IMG_PX, off)], fill=(255, 255, 255, 55), width=1)

    for m, col in ((10, (80, 200, 255, 190)), (20, (255, 200, 60, 190)),
                   (30, (255, 110, 110, 190))):
        r = m * ppm
        d.ellipse([c - r, c - r, c + r, c + r], outline=col, width=2)
        d.text((c + r - 30, c - 16), f"{m}m", fill=col)

    d.line([(c - 16, c), (c + 16, c)], fill=(255, 40, 40, 255), width=3)
    d.line([(c, c - 16), (c, c + 16)], fill=(255, 40, 40, 255), width=3)

    # 20 m scale bar, bottom-left, above the attribution strip
    x0, y0 = 30, IMG_PX - 110
    d.rectangle([x0 - 8, y0 - 26, x0 + 20 * ppm + 8, y0 + 14], fill=(0, 0, 0, 150))
    d.line([(x0, y0), (x0 + 20 * ppm, y0)], fill=(255, 255, 255, 255), width=4)
    d.text((x0, y0 - 22), "20 m", fill=(255, 255, 255, 255))

    im.save(dest)
    return True


def cmd_select(n: int) -> int:
    if not FIRST.exists():
        print(f"Missing {FIRST} — run 17_ingest_extent_annotations.py first.")
        return 1
    first = pd.read_csv(FIRST)
    rng = np.random.default_rng(SEED)
    pick = first.sample(n=min(n, len(first)), random_state=SEED)[
        ["point_id", "tile_id", "region"]].reset_index(drop=True)

    REVIEW.mkdir(parents=True, exist_ok=True)
    ok = 0
    for r in pick.itertuples():
        if render(r.point_id, REVIEW / f"{r.point_id}.png"):
            ok += 1
        else:
            print(f"  ! no crop for {r.point_id}")

    pick.to_csv(SAMPLE, index=False)
    if not SECOND.exists():
        tmpl = pick.copy()
        tmpl["box_w_m"] = ""
        tmpl["box_h_m"] = ""
        tmpl["note"] = ""
        tmpl.to_csv(SECOND, index=False)

    print(f"Selected {len(pick)} sites (seed {SEED}), rendered {ok} crops")
    print(f"  crops    -> {REVIEW}")
    print(f"  fill in  -> {SECOND}  (box_w_m, box_h_m)")
    print("\nFirst-pass values deliberately NOT shown — see BLINDING in docstring.")
    return 0


def cmd_agree() -> int:
    if not SECOND.exists():
        print(f"Missing {SECOND} — run `select` first.")
        return 1
    first = pd.read_csv(FIRST)
    second = pd.read_csv(SECOND)
    second = second.dropna(subset=["box_w_m", "box_h_m"])
    if second.empty:
        print("No second-read measurements recorded yet.")
        return 1

    second["area_equiv_m"] = np.sqrt(
        second["box_w_m"].astype(float) * second["box_h_m"].astype(float))
    m = first[["point_id", "region", "area_equiv_m"]].merge(
        second[["point_id", "area_equiv_m"]], on="point_id",
        suffixes=("_first", "_second"))
    if m.empty:
        print("No overlap between first and second reads.")
        return 1

    a, b = m["area_equiv_m_first"].to_numpy(), m["area_equiv_m_second"].to_numpy()
    diff = b - a
    mean = (a + b) / 2

    # Bland-Altman: bias and 95% limits of agreement.
    bias, sd = float(diff.mean()), float(diff.std(ddof=1))
    loa = (bias - 1.96 * sd, bias + 1.96 * sd)

    # Relative spread is the more useful figure when sizes span 4-35 m.
    rel = diff / mean
    # Lin's concordance correlation coefficient.
    va, vb = a.var(ddof=0), b.var(ddof=0)
    cov = ((a - a.mean()) * (b - b.mean())).mean()
    ccc = 2 * cov / (va + vb + (a.mean() - b.mean()) ** 2)

    print("=" * 72)
    print("Extent — agreement between first and second independent reads")
    print("=" * 72)
    print(f"\nn = {len(m)} sites\n")
    print(f"  {'site':<20}{'first':>8}{'second':>8}{'diff':>8}")
    for r in m.itertuples():
        print(f"  {r.point_id:<20}{r.area_equiv_m_first:>8.1f}"
              f"{r.area_equiv_m_second:>8.1f}"
              f"{r.area_equiv_m_second - r.area_equiv_m_first:>+8.1f}")

    print(f"\n  median, first read        {np.median(a):.1f} m")
    print(f"  median, second read       {np.median(b):.1f} m")
    print(f"  bias (second - first)     {bias:+.2f} m")
    print(f"  95% limits of agreement   [{loa[0]:+.1f}, {loa[1]:+.1f}] m")
    print(f"  mean absolute difference  {np.abs(diff).mean():.2f} m")
    print(f"  median relative diff      {np.median(np.abs(rel)) * 100:.0f}%")
    print(f"  Lin's concordance (CCC)   {ccc:.3f}")
    print(f"  Pearson r                 {np.corrcoef(a, b)[0, 1]:.3f}")

    # ---- Does the disagreement reach the decision the number feeds? --------
    #
    # Per-site limits of agreement are wide, but the figure that matters is the
    # MEDIAN, whose sampling error is much smaller. And the decision is binary:
    # is a dumpsite resolvable by a 30 m EnMAP pixel? That needs a 30 m site.
    rng = np.random.default_rng(SEED)
    idx = rng.integers(0, len(a), size=(4000, len(a)))
    med_a = np.median(a[idx], axis=1)
    med_b = np.median(b[idx], axis=1)
    dm = med_b - med_a

    print(f"\n  Median with 95% bootstrap CI:")
    for lbl, m_ in (("first", med_a), ("second", med_b)):
        print(f"    {lbl:<8} {np.median(m_):>5.1f} m  "
              f"[{np.percentile(m_, 2.5):.1f}, {np.percentile(m_, 97.5):.1f}]")
    print(f"    difference of medians {dm.mean():+.1f} m  "
          f"[{np.percentile(dm, 2.5):+.1f}, {np.percentile(dm, 97.5):+.1f}]")

    print(f"\n  Decision: is a median dumpsite resolvable at 30 m (EnMAP)?")
    for lbl, m_ in (("first", med_a), ("second", med_b)):
        med = float(np.median(m_))
        hi = float(np.percentile(m_, 97.5))
        print(f"    {lbl:<8} median {med:>5.1f} m -> {med**2/900:.2f} px   "
              f"(upper CI {hi:.1f} m -> {hi**2/900:.2f} px)")
    p30 = float((med_a >= 30).mean()), float((med_b >= 30).mean())
    print(f"    P(median site >= 30 m): first {p30[0]:.1%}, second {p30[1]:.1%}")
    print("    -> both reads leave the dumpsite sub-pixel; the disagreement is")
    print("       about absolute size, not about the conclusion it feeds.")

    out_decision = {
        "median_first_ci": [float(np.percentile(med_a, 2.5)),
                            float(np.percentile(med_a, 97.5))],
        "median_second_ci": [float(np.percentile(med_b, 2.5)),
                             float(np.percentile(med_b, 97.5))],
        "median_diff": float(dm.mean()),
        "median_diff_ci": [float(np.percentile(dm, 2.5)),
                           float(np.percentile(dm, 97.5))],
        "p_median_ge_30m": {"first": p30[0], "second": p30[1]},
    }

    out = {"n": int(len(m)), "bias_m": bias, "sd_m": sd,
           "loa95_m": list(loa), "mean_abs_diff_m": float(np.abs(diff).mean()),
           "median_rel_diff": float(np.median(np.abs(rel))),
           "ccc": float(ccc), "pearson_r": float(np.corrcoef(a, b)[0, 1]),
           "median_first_m": float(np.median(a)),
           "median_second_m": float(np.median(b)),
           "second_reader": "AI assistant (reproducibility, NOT human inter-rater)",
           **out_decision}
    with open(RUN / "extent_agreement.json", "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=2)
    m.to_csv(RUN / "extent_agreement_pairs.csv", index=False)
    print(f"\nWritten to {RUN / 'extent_agreement.json'}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["select", "agree"])
    ap.add_argument("--n", type=int, default=12)
    a = ap.parse_args()
    return cmd_select(a.n) if a.cmd == "select" else cmd_agree()


if __name__ == "__main__":
    raise SystemExit(main())
