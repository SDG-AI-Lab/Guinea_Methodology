"""
22 — Second independent read of dumpsite extent, and agreement with the first.

WHY
---
`Methodology_PlasticCharacterisation_Guinea.docx` §1.3 and §7 declare that the
dumpsite size distribution rests on a single interpreter with no agreement
estimate. That is the same limitation the marine methodology declares for its
own photo-interpretation, and it is what keeps the figure "provisional" rather
than quotable.

This script supports a second read of a random subsample and computes agreement
against the first.

WHAT THIS IS, AND IS NOT
------------------------
The second read here is performed by the AI assistant, not by a second human
analyst. That is a **reproducibility estimate** — how stable is the extent
judgement when the same imagery is measured again independently — and it is NOT
an inter-rater agreement figure between two human interpreters. The distinction
matters because a model reader and a human reader may share or differ in
systematic biases in ways two humans would not, and the document must say which
one it has.

BLINDING
--------
`select` writes the sample and renders the crops WITHOUT ever printing or
embedding the first-pass measurement. The second reader records values into
`second_read.csv`, and only `agree` joins the two. If the first-pass value is
visible before the second is recorded, the exercise measures nothing.

SAMPLING
--------
A uniform random subsample of the sites the first pass measured, with a fixed
seed. Deliberately NOT stratified by first-pass size: stratifying would condition
the sample on the very values under test.

Usage:
  python plasticwaste_tool/22_extent_second_read.py select --n 12
  ... second reader fills in runs/dumpsite_extent/second_read.csv ...
  python plasticwaste_tool/22_extent_second_read.py agree
"""
