"""
13 — Does the existing FDI code respond on land at labelled dumpsites?

Task 3 of `docs/DPWMS_Plastic_Characterisation_Plan.md` §7, and the last of the
three cheap gates. It costs almost nothing: `spectral.compute_fdi` is a pure
numpy function of B4/B6/B8/B11, and script 11 extracts those bands at every
labelled point (B6 since the FDI band correction). No new Earth Engine fetch is needed for the index itself.

NOTHING IN `spectral.py` OR `api_connector.py` IS MODIFIED. They are imported
and called as-is.

WHAT IS ACTUALLY BEING ASKED
----------------------------
The plan expects FDI to behave poorly on land because it assumes a water
background. But "poorly" can mean two very different things, and they have
opposite implications:

  (a) FDI is FLAT on land -> no signal, dead end, nothing more to say.
  (b) FDI is HIGH on land but NON-SPECIFIC -> it fires on dumps *and* on every
      other bare bright surface, so it looks like a detector and is not one.

This project has already recorded evidence for (b), in the FDI module itself.
`api_connector._surface_water_mask` (api_connector.py:252-258) exists precisely
because:

    "those two only exclude vegetation and open water, so every non-vegetated,
     non-water pixel survives -- bare soil, sand, concrete, port and industrial
     rooftops. Those have strong NIR/SWIR, hence a large FDI excess, so they
     were landing in the HIGH confidence band."

So the prediction is (b): FDI will respond at dumpsites, and the response will
be the same false-positive mechanism that forced a positive water constraint
into the marine pipeline. A raw AP number would look encouraging and mean
nothing. This script therefore tests two separate things:

  1. Does raw FDI separate dumps from non-dumps, and does it beat NDVI?
     (Same protocol as script 12, so the numbers are directly comparable.)
  2. Does the FDI *pipeline*, with its real masks, produce any output on land
     at all? The water constraint is a positive requirement, so the expected
     answer is zero surviving pixels - which is a statement about the pipeline
     being correctly scoped, not about dumpsites.

Run:  python plasticwaste_tool/13_fdi_on_land.py
Out:  plasticwaste_tool/runs/fdi_on_land/fdi_land_evaluation.json
"""
