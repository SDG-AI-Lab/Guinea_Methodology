def compute_fdi_on_samples(df: pd.DataFrame) -> pd.DataFrame:
    """Call the project's own FDI implementation, unmodified."""
    from plasticwaste_tool.spectral import compute_fdi, compute_ndvi, compute_ndwi

    need = ["B3", "B4", "B6", "B8", "B8A", "B11"]
    missing = [b for b in need if b not in df.columns]
    if missing:
        raise KeyError(
            f"s2_index_samples.csv lacks {missing}. The FDI now uses B6 (Biermann "
            "et al. 2020's RE2 band); re-run the Sentinel-2 sample extraction "
            "(characterisation_tool/s2_indices.py) so the CSV carries it.")
    bands = {b: df[b].to_numpy(dtype="float64") for b in need}
    df = df.copy()
    df["FDI"] = compute_fdi(bands)
    df["FDI_NDVI"] = compute_ndvi(bands)
    df["FDI_NDWI"] = compute_ndwi(bands)
    return df


def evaluate_fdi(df: pd.DataFrame, footprint: str, ev) -> Dict:
    sub = df[df["footprint"] == footprint].dropna(subset=["B11", "FDI"]).copy()
    y = sub["label"].to_numpy()
    tiles = sub["tile_id"].to_numpy()
    prevalence = float(y.mean())

    print(f"\n{'=' * 74}\nFOOTPRINT: {footprint}\n{'=' * 74}")
    print(f"  points {len(sub)}   positives {int(y.sum())}   "
          f"baseline AP {prevalence:.3f}")

    # Descriptive: is FDI even different between the two classes?
    pos, neg = sub[sub.label == 1]["FDI"], sub[sub.label == 0]["FDI"]
    print(f"  FDI at dumps     median {pos.median():+.5f}  "
          f"IQR [{pos.quantile(.25):+.5f}, {pos.quantile(.75):+.5f}]")
    print(f"  FDI at non-dumps median {neg.median():+.5f}  "
          f"IQR [{neg.quantile(.25):+.5f}, {neg.quantile(.75):+.5f}]")

    rng = np.random.default_rng(RNG_SEED)
    boot = ev.cluster_boot_indices(tiles, rng, N_BOOT)

    scores = {}
    boot_ap = {}
    for col in ["FDI", "NDVI", "PMLI"]:
        if col not in sub.columns:
            continue
        s = sub[col].to_numpy(dtype=float)
        ok = np.isfinite(s)
        ap, sign = ev.oriented_ap(y[ok], s[ok])
        reps = np.full(N_BOOT, np.nan)
        for i, idx in enumerate(boot):
            yy, ss = y[idx], s[idx]
            m = np.isfinite(ss)
            if m.sum() < 20 or yy[m].sum() < 2 or yy[m].sum() == m.sum():
                continue
            reps[i] = average_precision_score(yy[m], sign * ss[m])
        boot_ap[col] = reps
        lo, hi = np.nanpercentile(reps, [2.5, 97.5])
        scores[col] = {"ap": float(ap), "sign": int(sign),
                       "ci95": [float(lo), float(hi)],
                       "lift": float(ap / prevalence)}
        print(f"  {col:<6} AP={ap:.3f}  [{lo:.3f}, {hi:.3f}]  "
              f"lift={ap / prevalence:.2f}  dir={'+' if sign > 0 else '-'}")

    comps = {}
    for a, b in [("FDI", "NDVI"), ("FDI", "PMLI")]:
        if a not in boot_ap or b not in boot_ap:
            continue
        d = boot_ap[a] - boot_ap[b]
        d = d[np.isfinite(d)]
        lo, hi = np.percentile(d, [2.5, 97.5])
        sig = bool(lo > 0 or hi < 0)
        comps[f"{a}_minus_{b}"] = {"delta_ap": float(d.mean()),
                                   "ci95": [float(lo), float(hi)],
                                   "excludes_zero": sig}
        print(f"    {a} - {b}: dAP={d.mean():+.3f} [{lo:+.3f}, {hi:+.3f}]  "
              f"{'SIGNIFICANT' if sig else 'not significant'}")

    d0 = boot_ap["FDI"] - prevalence
    d0 = d0[np.isfinite(d0)]
    lo, hi = np.percentile(d0, [2.5, 97.5])
    comps["FDI_minus_baseline"] = {"delta_ap": float(d0.mean()),
                                   "ci95": [float(lo), float(hi)],
                                   "excludes_zero": bool(lo > 0)}
    print(f"    FDI - baseline: dAP={d0.mean():+.3f} [{lo:+.3f}, {hi:+.3f}]  "
          f"{'SIGNIFICANT' if lo > 0 else 'not significant'}")

    return {"footprint": footprint, "n": int(len(sub)),
            "n_positive": int(y.sum()), "baseline": prevalence,
            "scores": scores, "comparisons": comps,
            "fdi_median_dump": float(pos.median()),
            "fdi_median_nondump": float(neg.median())}


def test_pipeline_masks(df: pd.DataFrame, footprint: str) -> Dict:
    """
    Run the FDI module's own masking function on the land samples.

    `apply_spectral_masks` takes the WATER band as a POSITIVE constraint. The
    question is how many labelled dumpsites survive it. This is not a criticism
    of the marine pipeline - the constraint is there deliberately and for a
    documented reason - it is a demonstration that the pipeline is scoped to
    water and cannot be pointed at land without removing the very thing that
    makes its output trustworthy.
    """
    from plasticwaste_tool.spectral import apply_spectral_masks

    sub = df[df["footprint"] == footprint].dropna(subset=["FDI"]).copy()
    fdi = sub["FDI"].to_numpy(dtype="float64")
    ndvi = sub["FDI_NDVI"].to_numpy(dtype="float64")
    ndwi = sub["FDI_NDWI"].to_numpy(dtype="float64")
    is_dump = sub["label"].to_numpy() == 1

    # (a) NDVI/NDWI exclusions only — the "leakier" path, water=None.
    no_water = apply_spectral_masks(fdi, ndvi, ndwi, water=None)
    # (b) The real configuration: land is not permanent surface water, so the
    #     WATER band is 0 everywhere here.
    with_water = apply_spectral_masks(fdi, ndvi, ndwi,
                                      water=np.zeros_like(fdi))

    res = {
        "footprint": footprint,
        "n_points": int(len(sub)),
        "n_dumps": int(is_dump.sum()),
        "survive_ndvi_ndwi_only": int(np.isfinite(no_water).sum()),
        "dumps_survive_ndvi_ndwi_only": int(np.isfinite(no_water[is_dump]).sum()),
        "survive_with_water_constraint": int(np.isfinite(with_water).sum()),
        "dumps_survive_with_water_constraint": int(np.isfinite(with_water[is_dump]).sum()),
    }
    print(f"\n  Pipeline masks ({footprint}):")
    print(f"    NDVI/NDWI exclusions only : {res['survive_ndvi_ndwi_only']}"
          f"/{res['n_points']} points survive "
          f"({res['dumps_survive_ndvi_ndwi_only']}/{res['n_dumps']} dumps)")
    print(f"    + WATER positive constraint: "
          f"{res['survive_with_water_constraint']}/{res['n_points']} points survive "
          f"({res['dumps_survive_with_water_constraint']}/{res['n_dumps']} dumps)")
    return res


def check_worldcover_water(df: pd.DataFrame) -> Dict:
    """
    Empirically confirm the water constraint zeroes out the dumpsites, rather
    than asserting it. Samples ESA WorldCover (the layer
    `_surface_water_mask` uses) at every labelled dump point and counts how
    many fall on class 80, permanent water.
    """
    print("\n  Sampling ESA WorldCover at labelled dump points ...")
    if not init_gee_project_convention(verbose=True):
        return {"status": "error", "error": "GEE init failed"}
    import ee

    pts = df[(df.footprint == "native_pixel") & (df.label == 1)][
        ["point_id", "lon", "lat"]].drop_duplicates("point_id")
    feats = [ee.Feature(ee.Geometry.Point([r.lon, r.lat]), {"point_id": r.point_id})
             for r in pts.itertuples()]
    wc = ee.ImageCollection("ESA/WorldCover/v200").first().select("Map")
    sampled = wc.reduceRegions(ee.FeatureCollection(feats),
                               ee.Reducer.first(), 10).getInfo()

    classes = {}
    per_point = []
    lookup = pts.set_index("point_id")
    for f in sampled["features"]:
        v = f["properties"].get("first")
        pid = f["properties"].get("point_id")
        classes[str(v)] = classes.get(str(v), 0) + 1
        row = lookup.loc[pid] if pid in lookup.index else None
        per_point.append({"point_id": pid, "worldcover": v,
                          "lon": float(row.lon) if row is not None else None,
                          "lat": float(row.lat) if row is not None else None})
    # Saved per-point so the workflow notebook can map it without re-querying GEE.
    pd.DataFrame(per_point).to_csv(OUT_DIR / "worldcover_at_dumps.csv", index=False)

    names = {"10": "tree cover", "20": "shrubland", "30": "grassland",
             "40": "cropland", "50": "built-up", "60": "bare/sparse",
             "70": "snow/ice", "80": "permanent water", "90": "herb. wetland",
             "95": "mangroves", "100": "moss/lichen"}
    print("    WorldCover class at dump points:")
    for k, v in sorted(classes.items(), key=lambda x: -x[1]):
        print(f"      {names.get(k, k):<18} {v}")
    on_water = classes.get("80", 0)
    print(f"    -> {on_water}/{len(pts)} dump points are on permanent water "
          f"(WorldCover class 80)")
    return {"status": "ok", "n_points": int(len(pts)),
            "class_counts": classes, "on_permanent_water": int(on_water)}


def main() -> int:
    if not SAMPLES_CSV.exists():
        print(f"Missing {SAMPLES_CSV} — run 11_s2_plastic_indices.py first.")
        return 1
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    print("=" * 74)
    print("Task 3 — FDI response on land at labelled dumpsites")
    print("=" * 74)

    ev = _load_eval_helpers()
    df = pd.read_csv(SAMPLES_CSV).replace([np.inf, -np.inf], np.nan)
    df = compute_fdi_on_samples(df)

    out = {"n_boot": N_BOOT, "footprints": {}, "pipeline_masks": {}}
    for fp in sorted(df["footprint"].unique()):
        out["footprints"][fp] = evaluate_fdi(df, fp, ev)
        out["pipeline_masks"][fp] = test_pipeline_masks(df, fp)

    out["worldcover_at_dumps"] = check_worldcover_water(df)

    with open(OUT_DIR / "fdi_land_evaluation.json", "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=2)
    print(f"\nWritten to {OUT_DIR / 'fdi_land_evaluation.json'}")
    return 0


