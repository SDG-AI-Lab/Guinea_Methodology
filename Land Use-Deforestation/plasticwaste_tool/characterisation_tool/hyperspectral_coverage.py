def _get_json(url: str, params: Optional[Dict[str, Any]] = None,
              headers: Optional[Dict[str, str]] = None) -> Tuple[Dict[str, Any], Dict[str, str]]:
    """GET returning (parsed_json, response_headers). Raises on transport error."""
    if params:
        url = f"{url}?{urllib.parse.urlencode(params)}"
    # `headers={}` must stay empty, so test for None rather than falsiness --
    # see check_dlr_stac for why sending any Accept header there breaks.
    req = urllib.request.Request(
        url, headers={"Accept": "application/json"} if headers is None else headers)
    with urllib.request.urlopen(req, timeout=HTTP_TIMEOUT) as resp:
        raw = resp.read().decode("utf-8")
        hdrs = {k.lower(): v for k, v in resp.headers.items()}
    return json.loads(raw), hdrs


def _post_json(url: str, payload: Dict[str, Any]) -> Dict[str, Any]:
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        url, data=data,
        headers={"Content-Type": "application/json", "Accept": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=HTTP_TIMEOUT) as resp:
        return json.loads(resp.read().decode("utf-8"))


