def load_dump_points() -> List[Tuple[float, float, str]]:
    """
    Return [(lon, lat, tile_id), ...] for every explicit dump coordinate.

    The `lat`/`long` fields are semicolon-separated where one 250 m cell holds
    several dumps, so a cell can contribute more than one point. Cell centres
    are deliberately NOT used: a 250 m cell is 4x4 EnMAP pixels and the dump
    may sit at its edge, so the centre is the wrong place to ask about.
    """
    with open(LABELS_PATH, "r", encoding="utf-8") as fh:
        gj = json.load(fh)

    pts: List[Tuple[float, float, str]] = []
    for feat in gj["features"]:
        props = feat["properties"]
        if str(props.get("label", "")) != "1":
            continue
        lat_raw, lon_raw = props.get("lat"), props.get("long")
        if not lat_raw or not lon_raw:
            continue
        lats = [s.strip() for s in str(lat_raw).split(";") if s.strip()]
        lons = [s.strip() for s in str(lon_raw).split(";") if s.strip()]
        if len(lats) != len(lons):
            print(f"  ! {props.get('tile_id')}: {len(lats)} lats vs {len(lons)} lons — skipped")
            continue
        for la, lo in zip(lats, lons):
            try:
                pts.append((float(lo), float(la), str(props.get("tile_id"))))
            except ValueError:
                print(f"  ! {props.get('tile_id')}: unparseable coord {la!r},{lo!r} — skipped")
    return pts


# --------------------------------------------------------------------------
# Geometry — point in polygon, no geopandas dependency
# --------------------------------------------------------------------------

def _point_in_ring(lon: float, lat: float, ring: List[Tuple[float, float]]) -> bool:
    """Standard ray-casting. `ring` is [(lon, lat), ...]."""
    inside = False
    n = len(ring)
    for i in range(n):
        x1, y1 = ring[i]
        x2, y2 = ring[(i + 1) % n]
        if (y1 > lat) != (y2 > lat):
            x_at = (x2 - x1) * (lat - y1) / (y2 - y1) + x1
            if lon < x_at:
                inside = not inside
    return inside


def _bbox_of(ring: List[Tuple[float, float]]) -> Tuple[float, float, float, float]:
    xs = [p[0] for p in ring]
    ys = [p[1] for p in ring]
    return min(xs), min(ys), max(xs), max(ys)


def _bbox_intersects(a: Tuple[float, float, float, float],
                     b: Tuple[float, float, float, float]) -> bool:
    return not (a[2] < b[0] or a[0] > b[2] or a[3] < b[1] or a[1] > b[3])


