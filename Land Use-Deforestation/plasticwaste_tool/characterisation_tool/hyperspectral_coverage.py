# Sentinel-2 MSI SWIR/NIR band centres and widths, nm (S2A).
S2_BANDS_NM = {
    "B8A": (864.7, 21),
    "B9":  (945.1, 20),
    "B11": (1613.7, 91),
    "B12": (2202.4, 175),
}

# Native spectral sampling of the hyperspectral missions, nm.
HYPERSPECTRAL_SAMPLING_NM = {"EMIT": 7.4, "EnMAP": 6.5, "PRISMA": 9.0}


def check_band_coverage() -> Dict[str, Any]:
    """
    Coverage of *land* is not the only question — coverage of the *wavelengths*
    matters just as much, and the answer here is not the intuitive one.

    Sentinel-2 has SWIR bands, so it is natural to assume it can see the C–H
    absorptions that identify plastic. It cannot. Both diagnostic features fall
    in gaps between its bands:

      1215 nm  sits between B9 (945 nm) and B11 (1614 nm)  — a 669 nm gap
      1730 nm  sits between B11 (1614 nm) and B12 (2202 nm) — a 589 nm gap

    So the plastic-mulch indices in Task 2 (PMLI, PGI, GDI) do NOT measure C–H
    absorption. They measure the broad shape of the SWIR continuum, which
    plastic sheeting happens to alter. That is a weaker, less specific signal
    than the literature's framing suggests, and it is why Task 2 is written as
    a falsification test rather than an implementation.

    EnMAP and EMIT, sampling at ~6.5–7.4 nm, resolve both features directly.
    """
    feature_results = {}
    for feat_nm in CH_FEATURES_NM:
        inside = [b for b, (c, w) in S2_BANDS_NM.items()
                  if (c - w / 2) <= feat_nm <= (c + w / 2)]
        below = max((c for c, _ in S2_BANDS_NM.values() if c < feat_nm), default=None)
        above = min((c for c, _ in S2_BANDS_NM.values() if c > feat_nm), default=None)
        feature_results[f"{feat_nm}nm"] = {
            "sentinel2_band_containing_it": inside or None,
            "nearest_s2_band_below_nm": below,
            "nearest_s2_band_above_nm": above,
            "s2_gap_width_nm": (round(above - below, 1)
                                if below is not None and above is not None else None),
            "resolved_by": [m for m, step in HYPERSPECTRAL_SAMPLING_NM.items()
                            if SENSOR_SPECS[m][0] <= feat_nm <= SENSOR_SPECS[m][1]],
        }

    return {
        "ch_features_nm": list(CH_FEATURES_NM),
        "sentinel2_samples_either_feature": any(
            v["sentinel2_band_containing_it"] for v in feature_results.values()),
        "per_feature": feature_results,
        "note": ("Sentinel-2 indices (PMLI/PGI/GDI) infer plastic from SWIR "
                 "continuum shape, not from C-H absorption. Hyperspectral "
                 "resolves the features directly."),
    }


def pixels_per_dumpsite(site_extent_m: float = 50.0) -> Dict[str, Any]:
    """
    How many pixels does a typical dumpsite actually occupy?

    This is the counterweight to the coverage result. Finer spectral sampling
    comes at the cost of coarser ground sampling, and for a ~50 m target the
    trade is severe. Sentinel-2's 20 m SWIR bands are spatially FINER than
    EnMAP (30 m) and far finer than EMIT (60 m).

    NOTE: 50 m is an assumption, not a measurement. Actual dumpsite extents in
    Guinea have not been digitised — the labels are 250 m cells plus a point,
    not polygons. Until extents are measured these numbers are illustrative.
    """
    gsds = {"Sentinel-2 SWIR (B11/B12)": 20, "EnMAP": 30, "EMIT": 60}
    area = site_extent_m ** 2
    return {
        "assumed_site_extent_m": site_extent_m,
        "caveat": "site extent is assumed, not measured; labels are points, not polygons",
        "pixels": {name: round(area / (g ** 2), 2) for name, g in gsds.items()},
    }


# --------------------------------------------------------------------------
# Complementarity — the two missions do not cover the same places
# --------------------------------------------------------------------------

def _point_region_map() -> Dict[str, str]:
    with open(LABELS_PATH, "r", encoding="utf-8") as fh:
        gj = json.load(fh)
    out: Dict[str, str] = {}
    for feat in gj["features"]:
        p = feat["properties"]
        if str(p.get("label", "")) != "1" or not p.get("lat"):
            continue
        lats = [s.strip() for s in str(p["lat"]).split(";") if s.strip()]
        lons = [s.strip() for s in str(p["long"]).split(";") if s.strip()]
        for la, lo in zip(lats, lons):
            try:
                out[f"{p['tile_id']}@{float(la):.5f},{float(lo):.5f}"] = str(p.get("region"))
            except ValueError:
                continue
    return out


def analyse_complementarity(summary: Dict[str, Any], cloud_thresh: float = 20.0) -> Dict[str, Any]:
    """
    EMIT and EnMAP have almost opposite coverage over Guinea, which is the
    single most useful thing this check found. Neither alone is sufficient;
    together they are near-complete. Reporting only the better of the two
    would understate what is available by a wide margin.

    Regional breakdown matters because spatial block cross-validation
    (Roberts et al. 2017) needs blocks in more than one place. Coverage
    concentrated entirely on Conakry would be a single block and could not be
    validated spatially at all.
    """
    regions = _point_region_map()

    def clear_points(mission: str) -> set:
        res = summary["missions"].get(mission, {})
        out: set = set()
        for it in res.get("items", []) or []:
            try:
                if float(it["cloud_cover"]) < cloud_thresh:
                    out.update(it["dump_points"])
            except (TypeError, ValueError, KeyError):
                continue
        return out

    emit, enmap = clear_points("EMIT"), clear_points("EnMAP")
    union = emit | enmap

    def by_region(pts: set) -> Dict[str, int]:
        counts: Dict[str, int] = {}
        for k in pts:
            r = regions.get(k, "unknown")
            counts[r] = counts.get(r, 0) + 1
        return dict(sorted(counts.items()))

    region_totals = by_region(set(regions))
    return {
        "cloud_threshold_pct": cloud_thresh,
        "n_points_total": len(regions),
        "emit_only": len(emit - enmap),
        "enmap_only": len(enmap - emit),
        "both": len(emit & enmap),
        "union": len(union),
        "uncovered": len(set(regions) - union),
        "uncovered_by_region": by_region(set(regions) - union),
        "region_totals": region_totals,
        "emit_by_region": by_region(emit),
        "enmap_by_region": by_region(enmap),
        "union_by_region": by_region(union),
    }


# --------------------------------------------------------------------------
# Main
# --------------------------------------------------------------------------

def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    print("=" * 74)
    print("Hyperspectral coverage check over Guinea")
    print("=" * 74)

    dump_points = load_dump_points()
    print(f"\nLabelled dumpsite points loaded: {len(dump_points)} "
          f"(from {LABELS_PATH.name})")

    summary: Dict[str, Any] = {
        "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "guinea_bbox": GUINEA_BBOX,
        "n_dump_points": len(dump_points),
        "sensor_specs": {
            k: {"min_nm": v[0], "max_nm": v[1], "gsd_m": v[2], "n_bands": v[3],
                "covers_ch_1215nm": v[0] <= CH_FEATURES_NM[0] <= v[1],
                "covers_ch_1730nm": v[0] <= CH_FEATURES_NM[1] <= v[1]}
            for k, v in SENSOR_SPECS.items()
        },
        "missions": {},
    }

    emit = check_emit_cmr(dump_points)
    if emit.get("status") == "ok":
        with open(OUT_DIR / "emit_granules.json", "w", encoding="utf-8") as fh:
            json.dump(emit.pop("_all_entries"), fh, indent=1)
    summary["missions"]["EMIT"] = emit

    enmap = check_dlr_stac("ENMAP_HSI_L2A", "EnMAP", dump_points)
    if enmap.get("status") == "ok":
        with open(OUT_DIR / "enmap_items.json", "w", encoding="utf-8") as fh:
            json.dump(enmap.pop("_all_items"), fh, indent=1)
    summary["missions"]["EnMAP"] = enmap

    desis = check_dlr_stac("DESIS_HSI_L2A", "DESIS", dump_points)
    if desis.get("status") == "ok":
        with open(OUT_DIR / "desis_items.json", "w", encoding="utf-8") as fh:
            json.dump(desis.pop("_all_items"), fh, indent=1)
    summary["missions"]["DESIS"] = desis

    summary["missions"]["PRISMA"] = check_prisma()
    summary["missions"]["EMIT_gee_crosscheck"] = check_emit_gee()
    summary["complementarity"] = analyse_complementarity(summary)
    summary["band_coverage"] = check_band_coverage()
    summary["pixels_per_dumpsite"] = pixels_per_dumpsite()

    with open(OUT_DIR / "coverage_summary.json", "w", encoding="utf-8") as fh:
        json.dump(summary, fh, indent=2)

    print("\n" + "=" * 74)
    print("SUMMARY")
    print("=" * 74)
    for name, res in summary["missions"].items():
        if res.get("status") != "ok":
            print(f"{name:22s} {res.get('status')}  {res.get('reason', res.get('error', ''))[:60]}")
            continue
        if "size_over_guinea_bbox" in res:
            print(f"{name:22s} EE size = {res['size_over_guinea_bbox']}")
            continue
        use = res.get("dump_point_usability", {})
        spec = summary["sensor_specs"].get(name, {})
        swir = "SWIR ok" if spec.get("covers_ch_1730nm") else "NO SWIR"
        print(f"{name:22s} {swir:8s} bbox={res.get('bbox_hits')}  "
              f"scenes_on_a_dump={res.get('items_containing_a_dump_point')}")
        print(f"{'':22s}          dumps with any scene   : "
              f"{use.get('points_with_any_scene')}/{use.get('total_dump_points')}")
        print(f"{'':22s}          dumps with <20% cloud  : "
              f"{use.get('points_with_a_scene_lt20pct_cloud')}/{use.get('total_dump_points')}"
              f"  (median {use.get('median_clear_scenes_per_point_lt20pct')} scenes each)")

    comp = summary["complementarity"]
    print("\n" + "-" * 74)
    print(f"COMPLEMENTARITY (scenes under {comp['cloud_threshold_pct']:.0f}% cloud)")
    print("-" * 74)
    print(f"  EMIT only {comp['emit_only']}   EnMAP only {comp['enmap_only']}   "
          f"both {comp['both']}   UNION {comp['union']}/{comp['n_points_total']}   "
          f"uncovered {comp['uncovered']}")
    print(f"  {'region':<12}{'total':>7}{'EMIT':>7}{'EnMAP':>7}{'union':>7}")
    for region, tot in comp["region_totals"].items():
        print(f"  {region:<12}{tot:>7}{comp['emit_by_region'].get(region, 0):>7}"
              f"{comp['enmap_by_region'].get(region, 0):>7}"
              f"{comp['union_by_region'].get(region, 0):>7}")

    bc = summary["band_coverage"]
    print("\n" + "-" * 74)
    print("SPECTRAL SAMPLING OF THE C-H ABSORPTION FEATURES")
    print("-" * 74)
    for feat, r in bc["per_feature"].items():
        s2 = r["sentinel2_band_containing_it"] or "NONE (falls in a gap)"
        print(f"  {feat:>8}  Sentinel-2: {s2}"
              + (f"  [{r['nearest_s2_band_below_nm']:.0f} -> {r['nearest_s2_band_above_nm']:.0f} nm,"
                 f" {r['s2_gap_width_nm']:.0f} nm wide]" if not r["sentinel2_band_containing_it"] else ""))
        print(f"{'':10}  resolved by: {', '.join(r['resolved_by'])}")

    ppd = summary["pixels_per_dumpsite"]
    print(f"\n  Pixels on a {ppd['assumed_site_extent_m']:.0f} m dumpsite "
          f"({ppd['caveat']}):")
    for name, n in ppd["pixels"].items():
        print(f"    {name:<28} {n:>6.2f}")

    print(f"\nWritten to {OUT_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
