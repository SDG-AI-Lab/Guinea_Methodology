def check_dlr_stac(collection: str, mission: str,
                   dump_points: List[Tuple[float, float, str]]) -> Dict[str, Any]:
    """
    SERVER QUIRK, cost an hour to find: this endpoint returns HTTP 500 for any
    request carrying an `Accept: application/json` header, which is the header
    a well-behaved STAC client sends by default. Send no Accept header at all
    and the identical query returns 200. Both the POST /search form and the
    GET form fail this way, so it reads as a content-negotiation bug rather
    than a malformed query. Do not "fix" this by adding the header back.
    """
    print(f"\n[{mission}] querying DLR EOC STAC ({collection}) ...")
    items: List[Dict[str, Any]] = []
    n_matched: Optional[int] = None

    url = f"{DLR_STAC_SEARCH}?" + urllib.parse.urlencode({
        "collections": collection,
        "bbox": ",".join(str(v) for v in GUINEA_BBOX),
        "limit": 100,
    })

    guard = 0
    while url and guard < 100:
        guard += 1
        try:
            page, _ = _get_json(url, headers={})
        except Exception as exc:
            if not items:
                return {"status": "error", "mission": mission, "collection": collection,
                        "error": f"{type(exc).__name__}: {exc}"}
            print(f"  ! pagination stopped after {len(items)}: {exc}")
            break

        if n_matched is None:
            n_matched = page.get("numberMatched")
            print(f"  STAC matched: {n_matched}")

        batch = page.get("features", []) or []
        if not batch:
            break
        items.extend(batch)

        nxt = next((l for l in page.get("links", []) if l.get("rel") == "next"), None)
        url = nxt.get("href") if nxt else None
        if len(items) % 500 == 0:
            print(f"  fetched {len(items)}")
        time.sleep(0.1)

    print(f"  retrieved {len(items)} items")

    # Point containment against item geometry.
    per_point: Dict[str, List[Dict[str, Any]]] = {}
    items_with_dump: List[Dict[str, Any]] = []
    for it in items:
        geom = it.get("geometry") or {}
        rings: List[List[Tuple[float, float]]] = []
        if geom.get("type") == "Polygon":
            rings = [[(c[0], c[1]) for c in geom["coordinates"][0]]]
        elif geom.get("type") == "MultiPolygon":
            rings = [[(c[0], c[1]) for c in poly[0]] for poly in geom["coordinates"]]
        if not rings:
            continue
        props = it.get("properties", {}) or {}
        cloud = props.get("eo:cloud_cover")
        matched: List[str] = []
        for lon, lat, tile_id in dump_points:
            for ring in rings:
                if not _bbox_intersects((lon, lat, lon, lat), _bbox_of(ring)):
                    continue
                if _point_in_ring(lon, lat, ring):
                    key = f"{tile_id}@{lat:.5f},{lon:.5f}"
                    matched.append(key)
                    per_point.setdefault(key, []).append(
                        {"id": it.get("id"), "cloud": cloud,
                         "datetime": props.get("datetime") or props.get("start_datetime")})
                    break
        if matched:
            items_with_dump.append({
                "id": it.get("id"),
                "datetime": props.get("datetime") or props.get("start_datetime"),
                "cloud_cover": cloud,
                "swir_status": props.get("enmap:statusSWIR"),
                "swir_channels_missing": props.get("enmap:swirNumberChannelsMissing"),
                "n_dump_points": len(matched),
                "dump_points": matched,
            })

    return {
        "status": "ok",
        "mission": mission,
        "collection": collection,
        "source": "DLR EOC STAC (GET /search; POST returns HTTP 500)",
        "bbox_hits": n_matched,
        "items_retrieved": len(items),
        "items_containing_a_dump_point": len(items_with_dump),
        "distinct_dump_points_covered": len(per_point),
        "total_dump_points": len(dump_points),
        "cloud_summary": _cloud_summary([i["cloud_cover"] for i in items_with_dump]),
        "dump_point_usability": _point_usability(per_point, len(dump_points)),
        "items": items_with_dump,
        "_all_items": items,
    }


# --------------------------------------------------------------------------
# Cloud — the constraint that actually decides usability in humid tropics
# --------------------------------------------------------------------------

def _cloud_summary(values: List[Any]) -> Dict[str, Any]:
    """
    Guinea has a long rainy season and cloud, not revisit, is what limits
    optical coverage. A raw scene count is therefore misleading on its own;
    every count below is repeated at cloud thresholds.
    """
    vals: List[float] = []
    for v in values:
        try:
            vals.append(float(v))
        except (TypeError, ValueError):
            continue
    if not vals:
        return {"n_with_cloud_metadata": 0}
    vals.sort()
    return {
        "n_with_cloud_metadata": len(vals),
        "median": vals[len(vals) // 2],
        "n_lt_10pct": sum(1 for v in vals if v < 10),
        "n_lt_20pct": sum(1 for v in vals if v < 20),
        "n_lt_50pct": sum(1 for v in vals if v < 50),
        "n_ge_80pct": sum(1 for v in vals if v >= 80),
    }


def _point_usability(per_point: Dict[str, List[Dict[str, Any]]],
                     total_points: int) -> Dict[str, Any]:
    """
    For each labelled dumpsite, how many scenes are actually usable?

    This is the number that decides Path B. "The mission covers Guinea" is not
    the question; "can I get a clear cube over THIS dump" is.
    """
    def clear_count(scenes: List[Dict[str, Any]], thresh: float) -> int:
        n = 0
        for s in scenes:
            try:
                if float(s["cloud"]) < thresh:
                    n += 1
            except (TypeError, ValueError, KeyError):
                continue
        return n

    with_any = len(per_point)
    with_lt20 = sum(1 for v in per_point.values() if clear_count(v, 20) > 0)
    with_lt10 = sum(1 for v in per_point.values() if clear_count(v, 10) > 0)
    counts_lt20 = sorted(clear_count(v, 20) for v in per_point.values())
    return {
        "total_dump_points": total_points,
        "points_with_any_scene": with_any,
        "points_with_a_scene_lt20pct_cloud": with_lt20,
        "points_with_a_scene_lt10pct_cloud": with_lt10,
        "median_clear_scenes_per_point_lt20pct": (
            counts_lt20[len(counts_lt20) // 2] if counts_lt20 else 0),
    }


