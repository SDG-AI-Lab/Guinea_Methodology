def _parse_cmr_polygons(entry: Dict[str, Any]) -> List[List[Tuple[float, float]]]:
    """
    CMR returns footprints as `polygons`: a list of lists whose single string
    is space-separated "lat lon lat lon ...". Note the LAT-FIRST ordering —
    getting this backwards silently produces a footprint over the wrong
    hemisphere and a coverage count of zero, which is exactly the kind of bug
    that would make us wrongly abandon Path B.
    """
    out: List[List[Tuple[float, float]]] = []
    for poly_group in entry.get("polygons", []) or []:
        for poly_str in poly_group:
            vals = [float(v) for v in poly_str.split()]
            ring = [(vals[i + 1], vals[i]) for i in range(0, len(vals), 2)]
            if len(ring) >= 3:
                out.append(ring)
    return out


def check_emit_cmr(dump_points: List[Tuple[float, float, str]]) -> Dict[str, Any]:
    """Page the whole CMR result set for EMIT L2A reflectance over Guinea."""
    print("\n[EMIT] querying NASA CMR ...")
    w, s, e, n = GUINEA_BBOX
    params = {
        "short_name": "EMITL2ARFL",
        "bounding_box": f"{w},{s},{e},{n}",
        "page_size": 2000,
    }

    entries: List[Dict[str, Any]] = []
    search_after: Optional[str] = None
    total_hits: Optional[int] = None

    while True:
        headers = {"Accept": "application/json"}
        if search_after:
            headers["CMR-Search-After"] = search_after
        try:
            data, hdrs = _get_json(CMR_GRANULE_URL, params, headers)
        except Exception as exc:
            return {"status": "error", "error": f"{type(exc).__name__}: {exc}"}

        if total_hits is None:
            total_hits = int(hdrs.get("cmr-hits", "0"))
            print(f"  CMR-Hits (bbox intersect): {total_hits}")

        batch = data.get("feed", {}).get("entry", []) or []
        entries.extend(batch)
        print(f"  fetched {len(entries)}/{total_hits}")

        search_after = hdrs.get("cmr-search-after")
        if not search_after or not batch or len(entries) >= (total_hits or 0):
            break
        time.sleep(0.2)

    # Which granules actually contain a labelled dumpsite point?
    per_point: Dict[str, List[Dict[str, Any]]] = {}
    granules_with_dump: List[Dict[str, Any]] = []

    for ent in entries:
        rings = _parse_cmr_polygons(ent)
        if not rings:
            continue
        cloud = ent.get("cloud_cover")
        matched: List[str] = []
        for lon, lat, tile_id in dump_points:
            for ring in rings:
                if not _bbox_intersects((lon, lat, lon, lat), _bbox_of(ring)):
                    continue
                if _point_in_ring(lon, lat, ring):
                    key = f"{tile_id}@{lat:.5f},{lon:.5f}"
                    matched.append(key)
                    per_point.setdefault(key, []).append(
                        {"id": ent.get("title"), "cloud": cloud,
                         "datetime": ent.get("time_start")})
                    break
        if matched:
            granules_with_dump.append({
                "id": ent.get("title"),
                "datetime": ent.get("time_start"),
                "cloud_cover": cloud,
                "n_dump_points": len(matched),
                "dump_points": matched,
            })

    n_geom = sum(1 for e in entries if _parse_cmr_polygons(e))
    return {
        "status": "ok",
        "mission": "EMIT",
        "collection": "EMITL2ARFL v001 (L2A surface reflectance, 60 m)",
        "source": "NASA CMR",
        "bbox_hits": total_hits,
        "granules_retrieved": len(entries),
        "granules_with_footprint": n_geom,
        "items_containing_a_dump_point": len(granules_with_dump),
        "distinct_dump_points_covered": len(per_point),
        "total_dump_points": len(dump_points),
        "cloud_summary_all_guinea": _cloud_summary([e.get("cloud_cover") for e in entries]),
        "cloud_summary": _cloud_summary([g["cloud_cover"] for g in granules_with_dump]),
        "dump_point_usability": _point_usability(per_point, len(dump_points)),
        "items": granules_with_dump,
        "_all_entries": entries,
    }


