CROP_LIMIT_M = 80.0
SENSORS = (("Sentinel-2 SWIR (B11/B12)", 20), ("EnMAP", 30), ("EMIT", 60))


def censored_quantile(values: np.ndarray, censored: np.ndarray,
                      q: float) -> Optional[float]:
    """
    Quantile of a right-censored sample, reported only when identifiable.

    Censored observations are known to be >= their recorded value. Sort
    ascending; a quantile is identifiable if the value at that rank is an
    exact (uncensored) observation, or if enough uncensored observations sit
    below it that the answer cannot change whatever the censored ones turn out
    to be. Returns None when the quantile is not identifiable.
    """
    order = np.argsort(values)
    v, c = values[order], censored[order]
    n = len(v)
    if n == 0:
        return None
    k = int(math.ceil(q * n)) - 1
    k = max(0, min(n - 1, k))
    # If everything at or below rank k is uncensored, the quantile is exact.
    if not c[:k + 1].any():
        return float(v[k])
    # Otherwise it is only identifiable if the censored ones all sit above it.
    if not c[k]:
        return float(v[k])
    return None


def summarise(df: pd.DataFrame, col: str, label: str) -> Dict:
    vals = df[col].to_numpy(dtype=float)
    cens = df["beyond_frame"].to_numpy(dtype=int).astype(bool)
    frac = float(cens.mean()) if len(cens) else float("nan")

    out = {"n": int(len(vals)), "censored_fraction": frac}
    print(f"\n  {label}  (n={len(vals)}, {frac:.0%} censored at {CROP_LIMIT_M:.0f} m)")
    for q, name in ((0.25, "p25"), (0.50, "median"), (0.75, "p75")):
        est = censored_quantile(vals, cens, q)
        if est is None:
            print(f"    {name:<7} >= {CROP_LIMIT_M:.0f} m  (not identifiable — too many censored)")
            out[name] = None
        else:
            print(f"    {name:<7} {est:>6.1f} m")
            out[name] = est
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=str(DEFAULT_CSV))
    args = ap.parse_args()

    csv = Path(args.csv)
    if not csv.exists():
        print(f"No annotations at {csv}\n"
              f"Run 16_build_extent_annotator.py, open\n"
              f"  plasticwaste_tool/manual_qa/annotate_extent.html\n"
              f"annotate, click Export CSV, and save it to that path.")
        return 1

    RUN_DIR.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(csv)
    for c in ("beyond_frame", "not_a_dump", "unclear"):
        if c not in df.columns:
            df[c] = 0
        df[c] = df[c].fillna(0).astype(int)

    print("=" * 74)
    print("Dumpsite extent from manual annotation")
    print("=" * 74)
    print(f"\nAnnotated sites: {len(df)}")
    print(f"  flagged not_a_dump : {int(df.not_a_dump.sum())}")
    print(f"  flagged unclear    : {int(df.unclear.sum())}")
    print(f"  extends past frame : {int(df.beyond_frame.sum())}")

    if int(df.not_a_dump.sum()):
        print("\n  Label corrections (excluded from extent):")
        for r in df[df.not_a_dump == 1].itertuples():
            print(f"    {r.tile_id:<18} {r.region:<12} {str(getattr(r, 'note', '') or '')[:44]}")

    usable = df[(df.not_a_dump == 0) & (df.unclear == 0)].copy()
    usable = usable.dropna(subset=["box_w_m", "box_h_m"])
    if usable.empty:
        print("\nNo usable measured sites yet.")
        return 1

    usable["longest_m"] = usable[["box_w_m", "box_h_m"]].max(axis=1)
    usable["area_equiv_m"] = np.sqrt(usable["box_w_m"] * usable["box_h_m"])

    print(f"\n{'-' * 74}")
    print("Extent distribution")
    print(f"{'-' * 74}")
    res = {
        "n_annotated": int(len(df)),
        "n_not_a_dump": int(df.not_a_dump.sum()),
        "n_unclear": int(df.unclear.sum()),
        "n_usable": int(len(usable)),
        "longest_side": summarise(usable, "longest_m", "longest side"),
        "area_equivalent": summarise(usable, "area_equiv_m", "area-equivalent side"),
    }

    # The decision number.
    med = res["area_equivalent"]["median"]
    print(f"\n{'-' * 74}")
    print("Pixels on a median dumpsite  (area-equivalent side)")
    print(f"{'-' * 74}")
    if med is None:
        print(f"  Median not identifiable — more than half the sites exceed the")
        print(f"  {CROP_LIMIT_M:.0f} m crop. Sites are LARGER than the crop can measure,")
        print(f"  which favours Path B. Re-crop at 250 m to quantify.")
        res["pixels"] = None
    else:
        print(f"  median area-equivalent side: {med:.1f} m")
        res["pixels"] = {}
        for name, gsd in SENSORS:
            px = med ** 2 / gsd ** 2
            verdict = "sub-pixel" if px < 1 else ("marginal" if px < 4 else "resolvable")
            print(f"    {name:<26} {gsd:>3} m   {px:>6.2f} px   {verdict}")
            res["pixels"][name] = {"gsd_m": gsd, "pixels": float(px), "verdict": verdict}

        print(f"\n  For reference, the assumption this replaces "
              f"(50 m) gives 6.25 / 2.78 / 0.69 px.")

    print(f"\n{'-' * 74}")
    print("By region (area-equivalent median, uncensored only)")
    print(f"{'-' * 74}")
    for reg, g in usable[usable.beyond_frame == 0].groupby("region"):
        print(f"  {reg:<14} n={len(g):>3}  median {g['area_equiv_m'].median():>6.1f} m")

    with open(RUN_DIR / "extent_annotated_summary.json", "w", encoding="utf-8") as fh:
        json.dump(res, fh, indent=2)
    usable.to_csv(RUN_DIR / "extent_annotated_usable.csv", index=False)
    print(f"\nWritten to {RUN_DIR}")
    return 0


