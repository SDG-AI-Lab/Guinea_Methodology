"""
17 — Turn annotated dumpsite extents into the pixel-count answer.

Consumes `extent_annotations.csv` exported by the tool that
`16_build_extent_annotator.py` generates, and produces the number that
`docs/DPWMS_Hyperspectral_Coverage_Findings.md` §5 currently assumes:
**how many sensor pixels does a real Guinean dumpsite occupy?**

Place the exported CSV at:
    plasticwaste_tool/runs/dumpsite_extent/extent_annotations.csv
(or pass --csv)

HOW CENSORING IS HANDLED
------------------------
The detail crop is 80 m across, so a site larger than that cannot be measured —
the annotator flags it "extends beyond frame" and the observation is
**right-censored**: known to be >= the box drawn, not equal to it.

Treating a censored value as if it were exact would bias every statistic
downward, which for this decision is the dangerous direction: it would make
dumpsites look smaller, hence less resolvable, hence Path B look worse than it
is. So censored observations are kept and handled explicitly:

  * A quantile is reported only if it is **identifiable** — i.e. it falls below
    the point where censoring takes over. If more than half the sample is
    censored the median is reported as a lower bound (">= 80 m"), not a number.
  * The censored fraction is always printed next to the estimate.

WHICH SITES COUNT
-----------------
Sites flagged `not_a_dump` are excluded from the extent distribution and
reported separately — they are a label correction, which is a useful output in
its own right given 54 of 55 positive cells carry low or medium confidence.
Sites flagged `unclear` are excluded from the headline and reported as a
sensitivity range.

TWO SIZE DEFINITIONS, BOTH REPORTED
-----------------------------------
  longest side   max(w, h) — how big the site is at its widest
  area-equivalent sqrt(w * h) — the side of a square of the same area

The pixel-count argument wants the **area-equivalent** figure, because what
matters is what fraction of a pixel the site fills, not its longest dimension.
A 60 x 5 m roadside strip is 60 m across and fills almost nothing.

Run:  python plasticwaste_tool/17_ingest_extent_annotations.py
"""
