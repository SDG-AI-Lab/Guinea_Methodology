"""
23 — Waste mobilisation and leakage risk at Guinean dumpsites.

Implements the concept note's "Waste Flow and Mobilization Modeling" activity:

    "By integrating the hotspot maps with data on rainfall, river networks
     (hydrology), and topography (DEMs), we can simulate how and when plastic
     from dumpsites mobilizes during the rainy season. This allows authorities
     to predict which river basins are at highest risk, identify optimal
     locations for river-based traps, and prioritize interventions before
     plastic reaches the ocean."

WHY THIS IS DELIVERABLE WHEN CHARACTERISATION IS NOT
----------------------------------------------------
Characterisation asks what a dumpsite is *made of*, which needs a per-site
material measurement no satellite can provide (gates 2-4). Mobilisation asks
where waste *goes*, which is a function of terrain, rainfall and drainage —
all of which are directly observable. It sidesteps the unknown rather than
depending on it.

LITERATURE BASIS
----------------
Two published model families, both reproduced here in reduced form:

* **Meijer, van Emmerik, van der Ent, Schmidt & Lebreton (2021)**, "More than
  1000 rivers account for 80% of global riverine plastic emissions into the
  ocean", Science Advances 7(18):eaaz5803. A probabilistic model combining
  mismanaged plastic waste, land use, wind, precipitation and river networks to
  compute the probability that waste reaches a river and then the ocean. Its
  two dominant geometric terms are **distance to the river network** and
  **distance to the basin outlet**: sources nearer either are likelier to be
  emitted.

* **The Plastic Pathfinder** (Mellink, van Emmerik et al.), a macroplastic
  transport and fate model at river-basin scale. Its governing principle is
  that waste is mobilised when **driving forces (surface runoff and wind)
  overcome terrain friction, which is a function of slope and land-use type**.
  Land-use-dependent thresholds are central: urban surfaces mobilise waste far
  more readily than forest.

A comparable GIS/remote-sensing leakage mapping approach for a developing
tropical basin is given for the Lower Mekong in Sustainability 14(13):7879.

WHAT IS AND IS NOT CLAIMED
--------------------------
This produces a **relative mobilisation-risk ranking across Guinea's detected
dumpsites**. It is NOT a plastic emission estimate in tonnes per year, for two
reasons that must travel with the output:

  1. **The plastic fraction of each dump is unknown** — that is precisely what
     gates 2-4 established cannot be measured from satellite. The mass term
     here is a *waste* proxy from measured site extent, and plastic is an
     unmeasured fraction of it.
  2. **There is no Guinean calibration data.** Meijer et al. calibrated against
     field observations from 2017-2020; no equivalent exists here. An
     uncalibrated probabilistic model gives defensible *ordering*, not
     defensible magnitudes.

Reporting this as "which dumpsites most likely leak waste to watercourses in
the rainy season" is supported. Reporting tonnes is not.

DATA
----
  Copernicus DEM GLO-30           terrain slope and flow direction
  WWF HydroSHEDS flow accumulation drainage network
  CHIRPS daily precipitation       wet-season runoff driver
  ESA WorldCover v200              land-use friction class
  JRC Global Surface Water         permanent water / ocean for the outlet term
  this project's dumpsite labels   source locations and measured extent

Run:  python plasticwaste_tool/23_waste_mobilisation_risk.py
Out:  plasticwaste_tool/runs/mobilisation/mobilisation_risk.csv (+ .json)
"""
