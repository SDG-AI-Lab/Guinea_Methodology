LABELS = TOOL / "manual_qa" / "regions" / "national_random_sample.geojson"
EXTENT = TOOL / "runs" / "dumpsite_extent" / "extent_annotated_usable.csv"
OUT_DIR = TOOL / "runs" / "mobilisation"

# Guinea's rainy season. The concept note asks specifically about rainy-season
# mobilisation, and CHIRPS over Dec-Mar would describe the wrong regime.
WET_MONTHS = [5, 6, 7, 8, 9, 10]
WET_YEARS = (2020, 2025)

# Flow-accumulation threshold (cells) defining a watercourse. HydroSHEDS 15ACC
# is ~500 m, so this is a basin-scale drainage network, not every gully.
ACC_THRESHOLD = 100

# Distance decay lengths, metres. Meijer et al. found emission probability falls
# sharply with distance to the river network; these are transparent scale
# parameters, NOT calibrated to Guinean observations.
L_RIVER = 2000.0
L_OCEAN = 150000.0

# Terrain friction by ESA WorldCover class, following the Plastic Pathfinder's
# land-use-dependent mobilisation thresholds (urban mobilises readily, forest
# resists). Expressed as relative friction, 1 = lowest resistance.
FRICTION = {
    50: 1.0,   # built-up — lowest friction, highest mobilisation
    60: 1.1,   # bare / sparse vegetation
    30: 1.6,   # grassland
    40: 1.8,   # cropland
    20: 2.2,   # shrubland
    95: 2.6,   # mangroves
    90: 2.6,   # herbaceous wetland
    10: 3.0,   # tree cover — highest friction
    80: 1.0,   # permanent water — already in the network
    70: 2.0,   # snow/ice (not present in Guinea)
}
DEFAULT_FRICTION = 2.0


def load_sites() -> pd.DataFrame:
    with open(LABELS, "r", encoding="utf-8") as fh:
        gj = json.load(fh)
    rows: List[Dict] = []
    for f in gj["features"]:
        p = f["properties"]
        if str(p.get("label")) != "1" or not p.get("lat"):
            continue
        lats = [s.strip() for s in str(p["lat"]).split(";") if s.strip()]
        lons = [s.strip() for s in str(p["long"]).split(";") if s.strip()]
        for i, (la, lo) in enumerate(zip(lats, lons)):
            rows.append({"point_id": f"{p['tile_id']}_p{i}",
                         "tile_id": p["tile_id"], "region": p.get("region"),
                         "lon": float(lo), "lat": float(la)})
    df = pd.DataFrame(rows)

    # Measured extent where available; median elsewhere. Extent stands in for
    # waste mass, and per the second-read agreement check it is reproducible
    # only as a size class, so it is binned rather than used continuously.
    if EXTENT.exists():
        ext = pd.read_csv(EXTENT)[["point_id", "area_equiv_m"]]
        df = df.merge(ext, on="point_id", how="left")
    else:
        df["area_equiv_m"] = np.nan
    med = df["area_equiv_m"].median()
    df["area_equiv_m"] = df["area_equiv_m"].fillna(med)
    df["size_class"] = pd.cut(df["area_equiv_m"], [0, 10, 20, 1e9],
                              labels=["small", "medium", "large"])
    df["mass_proxy"] = df["size_class"].map(
        {"small": 1.0, "medium": 2.0, "large": 4.0}).astype(float)
    return df


def extract_terms(df: pd.DataFrame) -> pd.DataFrame:
    import ee

    pts = ee.FeatureCollection([
        ee.Feature(ee.Geometry.Point([r.lon, r.lat]), {"point_id": r.point_id})
        for r in df.itertuples()])

    # SRTM rather than a Copernicus DEM mosaic: `.mosaic()` discards the
    # source projection, so ee.Terrain.slope() computes against a 1-degree
    # default and returns ~0 everywhere. Measured on an inland test point,
    # the mosaic gave 0.03 degrees where SRTM gave 14.3. Silent, and it would
    # have zeroed the entire slope term.
    dem = ee.Image("USGS/SRTMGL1_003")
    slope = ee.Terrain.slope(dem).rename("slope_deg")

    acc = ee.Image("WWF/HydroSHEDS/15ACC")
    network = acc.gte(ACC_THRESHOLD).selfMask()
    # Distance in metres from every pixel to the nearest watercourse.
    dist_river = (network.fastDistanceTransform(4096).sqrt()
                  .multiply(ee.Image.pixelArea().sqrt())
                  .rename("dist_river_m"))

    # Distance to the SEA, not to any permanent water. An earlier version used
    # JRC Global Surface Water occurrence >= 90, which counts the Milo and
    # Niger as "ocean" and made inland Kankan sites look coastal. Meijer et
    # al.'s term is distance to the basin OUTLET, so it must be the sea.
    # ETOPO1 bedrock < 0 is coarse (~1.8 km) but unambiguous at national scale.
    ocean = ee.Image("NOAA/NGDC/ETOPO1").select("bedrock").lt(0).selfMask()
    dist_ocean = (ocean.fastDistanceTransform(4096).sqrt()
                  .multiply(ee.Image.pixelArea().sqrt())
                  .rename("dist_ocean_m"))

    chirps = (ee.ImageCollection("UCSB-CHG/CHIRPS/DAILY")
              .filterDate(f"{WET_YEARS[0]}-01-01", f"{WET_YEARS[1]}-12-31")
              .filter(ee.Filter.Or(*[ee.Filter.calendarRange(m, m, "month")
                                     for m in WET_MONTHS])))
    n_years = WET_YEARS[1] - WET_YEARS[0] + 1
    wet_rain = chirps.sum().divide(n_years).rename("wet_rain_mm")

    lc = ee.ImageCollection("ESA/WorldCover/v200").first().select("Map").rename("worldcover")

    # Upstream catchment size at the nearest watercourse — a discharge proxy.
    # Added after the first flood validation: local rainfall alone ranked
    # observed-flooded sites INVERSELY (AUC 0.247), because the Kankan sites
    # that flood sit on the Niger/Milo floodplain where local rain is LOWER
    # than coastal Conakry. For a floodplain site the driver is upstream
    # discharge, not rain falling on the site — which is why Meijer et al. use
    # river discharge. Focal max over ~1 km so a site set back from the channel
    # still picks up its river's catchment rather than its own hillslope cell.
    upstream = (acc.focalMax(radius=1000, units="meters")
                .rename("upstream_acc"))

    stack = (slope.addBands(dist_river).addBands(dist_ocean)
             .addBands(wet_rain).addBands(lc).addBands(upstream))

    out: List[Dict] = []
    ids = df["point_id"].tolist()
    for start in range(0, len(ids), 120):
        batch = pts.filter(ee.Filter.inList("point_id", ids[start:start + 120]))
        got = stack.reduceRegions(batch, ee.Reducer.first(), 90).getInfo()
        for f in got["features"]:
            out.append(f["properties"])
        print(f"    {min(start + 120, len(ids))}/{len(ids)}")
    return df.merge(pd.DataFrame(out), on="point_id", how="left")


def observed_flooding(df: pd.DataFrame) -> pd.DataFrame:
    """
    Independent observational check: has each dumpsite actually been inundated?

    The Global Flood Database (Tellman et al. 2021, Nature 596:80-86) holds
    MODIS-derived flood extents for ~900 events worldwide, 8 of them over
    Guinea, all rain-driven. This is a *direct observation of the mobilisation
    mechanism* — a dumpsite that floods has demonstrably had water move through
    it — and it is entirely independent of the terrain, rainfall and drainage
    terms the risk score is built from.

    It is not calibration. Calibrating a plastic emission model needs observed
    plastic flux, which does not exist for Guinea. It is a concordance test of
    the hydrological half: if high-risk sites do not flood more often than
    low-risk ones, the score is not tracking anything real.

    Caveat: MODIS is ~250 m and our dumpsites are ~14 m, so this says the site's
    surroundings inundated, not the waste pile itself.
    """
    import ee

    gfd = ee.ImageCollection("GLOBAL_FLOOD_DB/MODIS_EVENTS/V1")
    aoi = ee.Geometry.Rectangle([-15.1, 7.1, -7.6, 12.8], None, False)
    sub = gfd.filterBounds(aoi)

    # "flooded" is per-event; sum across events = how many times inundated.
    n_events = sub.select("flooded").sum().rename("flood_count")
    ever = n_events.gt(0).rename("flood_ever")
    stack = n_events.addBands(ever)

    pts = ee.FeatureCollection([
        ee.Feature(ee.Geometry.Point([r.lon, r.lat]), {"point_id": r.point_id})
        for r in df.itertuples()])

    out: List[Dict] = []
    ids = df["point_id"].tolist()
    for start in range(0, len(ids), 120):
        batch = pts.filter(ee.Filter.inList("point_id", ids[start:start + 120]))
        got = stack.reduceRegions(batch, ee.Reducer.first(), 250).getInfo()
        for f in got["features"]:
            pr = f["properties"]
            out.append({"point_id": pr["point_id"],
                        "flood_count": pr.get("flood_count"),
                        "flood_ever": pr.get("flood_ever")})
    got = pd.DataFrame(out)
    got["flood_count"] = got["flood_count"].fillna(0)
    got["flood_ever"] = got["flood_ever"].fillna(0).astype(int)
    return df.merge(got, on="point_id", how="left")


def validate_against_flooding(d: pd.DataFrame) -> Dict:
    """
    Does each score, and each component, rank observed-flooded sites higher?

    Every component is reported, not just the headline, because the first
    version of this model hid an inverted term inside a single product. A
    component-wise table makes that failure visible instead of averaging it
    away.
    """
    from scipy.stats import mannwhitneyu
    from sklearn.metrics import average_precision_score, roc_auc_score

    y = d["flood_ever"].fillna(0).to_numpy().astype(int)
    if y.sum() < 3 or y.sum() == len(y):
        return {"status": "insufficient", "n_flooded": int(y.sum())}
    base = float(y.mean())

    def one(col):
        s = d[col].fillna(d[col].median()).to_numpy()
        _, pval = mannwhitneyu(s[y == 1], s[y == 0], alternative="greater")
        return {"auc": float(roc_auc_score(y, s)),
                "ap": float(average_precision_score(y, s)),
                "lift": float(average_precision_score(y, s) / base),
                "p": float(pval),
                "median_flooded": float(np.median(s[y == 1])),
                "median_unflooded": float(np.median(s[y == 0]))}

    cols = ["mobilisation_risk", "ocean_leakage_risk", "p_mobilise",
            "p_washoff", "p_inundation", "p_to_river", "p_to_ocean",
            "mass_proxy"]
    return {"status": "ok", "n_sites": int(len(y)), "n_flooded": int(y.sum()),
            "prevalence": base,
            "flooded_by_region": d.loc[y == 1, "region"].value_counts().to_dict(),
            "components": {c: one(c) for c in cols}}


def score(df: pd.DataFrame) -> pd.DataFrame:
    """
    Reduced Meijer-style emission score.

        risk = mass x P(mobilise) x P(reach watercourse) x P(reach ocean)

    Each term is bounded in [0, 1] and transparent. Terms are NOT calibrated
    against Guinean field observations — none exist — so the output supports
    ordering, not magnitude.
    """
    d = df.copy()

    # --- driving forces (Plastic Pathfinder) -------------------------------
    # Rainfall normalised across the national sample; slope capped at 15 deg,
    # beyond which additional steepness adds little for loose surface waste.
    rain = d["wet_rain_mm"].fillna(d["wet_rain_mm"].median())
    d["f_rain"] = (rain - rain.min()) / max(rain.max() - rain.min(), 1e-9)
    slope = d["slope_deg"].fillna(d["slope_deg"].median()).clip(0, 15)
    d["f_slope"] = slope / 15.0

    # --- terrain friction (land use) ---------------------------------------
    d["friction"] = d["worldcover"].map(FRICTION).fillna(DEFAULT_FRICTION)
    d["f_friction"] = 1.0 / d["friction"]

    # --- TWO mobilisation pathways, not one ---------------------------------
    #
    # The first version modelled only local wash-off and failed its flood
    # validation. Waste can enter a watercourse two physically distinct ways,
    # and they are driven by different things:
    #
    #   wash-off    rain falls ON the site, runoff carries waste downslope.
    #               Driven by local rainfall, slope, land-use friction.
    #   inundation  the river rises OVER the site. Driven by upstream
    #               catchment discharge, not by local rain at all.
    #
    # Meijer et al. capture both by routing runoff through the drainage
    # network; this reduced form represents them as separate probabilities and
    # combines them as a union — either mechanism suffices — rather than a
    # product, which would require both to occur.
    d["p_washoff"] = ((0.7 * d["f_rain"] + 0.3 * d["f_slope"])
                      * d["f_friction"]).clip(0, 1)

    # Discharge scales with catchment area over orders of magnitude, so the log
    # is the meaningful scale. Normalised across the national sample.
    acc = d["upstream_acc"].fillna(0).clip(lower=0)
    la = np.log1p(acc)
    d["f_discharge"] = ((la - la.min()) / max(la.max() - la.min(), 1e-9))
    d["p_inundation"] = d["f_discharge"]

    # Union of the two pathways.
    d["p_mobilise"] = 1.0 - (1.0 - d["p_washoff"]) * (1.0 - d["p_inundation"])

    # --- geometric terms (Meijer et al. 2021) -------------------------------
    d["p_to_river"] = np.exp(-d["dist_river_m"].fillna(1e5) / L_RIVER)
    d["p_to_ocean"] = np.exp(-d["dist_ocean_m"].fillna(1e6) / L_OCEAN)

    # TWO SCORES, NOT ONE. The first version multiplied everything into a single
    # number and it failed its flood validation at ROC-AUC 0.108 — strongly
    # INVERSE. The diagnosis: 11 of 13 observed-flooded sites are in Kankan,
    # 495 km inland on the Niger/Milo floodplain. The distance-to-sea term
    # correctly drove those to zero, which is right for ocean delivery and
    # wrong for local mobilisation. The two are different questions that pull
    # in opposite directions, and Meijer et al. keep them as separate terms for
    # exactly this reason.
    #
    #   mobilisation_risk  does waste leave the site into a watercourse?
    #                      -> the operational question for clean-up siting
    #   ocean_leakage_risk does it then reach the Atlantic?
    #                      -> the marine-plastic question
    #
    # The split is a conceptual correction from Meijer's structure, NOT a fit to
    # the 13 flooded sites; no weight below was tuned against them.
    d["mob_raw"] = d["mass_proxy"] * d["p_mobilise"] * d["p_to_river"]
    mx = d["mob_raw"].max()
    d["mobilisation_risk"] = 100.0 * d["mob_raw"] / mx if mx > 0 else 0.0

    d["ocean_raw"] = d["mob_raw"] * d["p_to_ocean"]
    mxo = d["ocean_raw"].max()
    d["ocean_leakage_risk"] = 100.0 * d["ocean_raw"] / mxo if mxo > 0 else 0.0

    # `risk_score` retained as the ocean-delivery variant for backward
    # compatibility with the layer table; the mobilisation score is the one
    # validated below.
    d["risk_score"] = d["ocean_leakage_risk"]
    d["risk_rank"] = d["risk_score"].rank(ascending=False, method="min").astype(int)
    d["risk_class"] = pd.cut(d["risk_score"], [-0.01, 5, 20, 50, 100],
                             labels=["low", "moderate", "high", "very high"])
    d["mobilisation_class"] = pd.cut(d["mobilisation_risk"], [-0.01, 5, 20, 50, 100],
                                     labels=["low", "moderate", "high", "very high"])
    return d


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    print("=" * 74)
    print("Waste mobilisation and leakage risk at Guinean dumpsites")
    print("=" * 74)

    if not init_gee_project_convention():
        return 1

    sites = load_sites()
    print(f"\n{len(sites)} dumpsite points, "
          f"{sites['size_class'].value_counts().to_dict()}")

    print("\nExtracting terrain, drainage, rainfall and land cover ...")
    d = extract_terms(sites)
    d = score(d)

    print("\nChecking observed flood inundation (Global Flood Database) ...")
    d = observed_flooding(d)
    val = validate_against_flooding(d)

    d.to_csv(OUT_DIR / "mobilisation_risk.csv", index=False)

    print(f"\n{'-' * 74}\nInput terms (national sample)\n{'-' * 74}")
    for col, unit in (("wet_rain_mm", "mm/yr wet season"),
                      ("slope_deg", "degrees"),
                      ("dist_river_m", "m to watercourse"),
                      ("dist_ocean_m", "m to ocean"),
                      ("upstream_acc", "upstream cells (discharge proxy)")):
        v = d[col].dropna()
        print(f"  {col:<16} median {v.median():>10.0f}  "
              f"p10 {v.quantile(.1):>10.0f}  p90 {v.quantile(.9):>10.0f}   {unit}")

    print(f"\n{'-' * 74}\nRisk class distribution\n{'-' * 74}")
    for k, n in d["risk_class"].value_counts().sort_index().items():
        print(f"  {str(k):<12} {n:>4}")

    print(f"\n{'-' * 74}\nTop 12 dumpsites by mobilisation risk\n{'-' * 74}")
    print(f"  {'rank':>4} {'site':<18}{'region':<11}{'score':>7}"
          f"{'size':>8}{'rain':>7}{'d_riv':>8}{'d_sea':>9}")
    top = d.nsmallest(12, "risk_rank")
    for r in top.itertuples():
        print(f"  {r.risk_rank:>4} {r.point_id:<18}{str(r.region):<11}"
              f"{r.risk_score:>7.1f}{str(r.size_class):>8}"
              f"{r.wet_rain_mm:>7.0f}{r.dist_river_m:>8.0f}{r.dist_ocean_m:>9.0f}")

    print(f"\n{'-' * 74}\nBy region (mean risk score)\n{'-' * 74}")
    for reg, g in d.groupby("region"):
        print(f"  {reg:<12} n={len(g):>3}  mean {g['risk_score'].mean():>6.1f}  "
              f"max {g['risk_score'].max():>6.1f}")

    print(f"\n{'-' * 74}")
    print("Independent check: does the score rank observed-flooded sites higher?")
    print(f"{'-' * 74}")
    if val.get("status") == "ok":
        print(f"  sites inundated in an observed flood: {val['n_flooded']}"
              f"/{val['n_sites']}  ({val['prevalence']:.0%})")
        print(f"  flooded by region: {val['flooded_by_region']}")
        print("")
        print(f"  {'component':<20}{'AUC':>7}{'AP':>7}{'lift':>6}{'p':>8}   verdict")
        for c, v in val["components"].items():
            verdict = ("predicts flooding" if v["auc"] > 0.65 else
                       "INVERSE" if v["auc"] < 0.35 else "no signal")
            print(f"  {c:<20}{v['auc']:>7.3f}{v['ap']:>7.3f}"
                  f"{v['lift']:>6.2f}{v['p']:>8.3f}   {verdict}")
        print("")
        print("  A concordance test of the hydrological half, not a calibration:")
        print("  calibrating an emission model needs observed plastic flux, which")
        print("  does not exist for Guinea.")
    else:
        print(f"  insufficient flooded sites ({val.get('n_flooded')}) to test")

    summary = {
        "flood_validation": val,
        "n_sites": int(len(d)),
        "wet_months": WET_MONTHS, "wet_years": WET_YEARS,
        "acc_threshold_cells": ACC_THRESHOLD,
        "decay_river_m": L_RIVER, "decay_ocean_m": L_OCEAN,
        "friction_by_worldcover": FRICTION,
        "risk_class_counts": {str(k): int(v) for k, v
                              in d["risk_class"].value_counts().items()},
        "region_mean_risk": {k: float(v) for k, v
                             in d.groupby("region")["risk_score"].mean().items()},
        "calibrated": False,
        "caveat": ("relative ranking only; plastic fraction of each dump is "
                   "unknown and no Guinean calibration data exists"),
    }
    with open(OUT_DIR / "mobilisation_summary.json", "w", encoding="utf-8") as fh:
        json.dump(summary, fh, indent=2)
    print(f"\nWritten to {OUT_DIR}")
    return 0


