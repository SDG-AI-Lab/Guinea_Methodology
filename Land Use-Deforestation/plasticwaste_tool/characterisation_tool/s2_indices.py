def build_dry_season_composite():
    import ee

    def mask_land_clear(img):
        scl = img.select("SCL")
        keep = ee.Image.constant(0)
        for c in SCL_CLEAR_LAND:
            keep = keep.Or(scl.eq(c))
        return img.updateMask(keep).divide(10000).copyProperties(img, ["system:time_start"])

    # DRY_MONTHS wraps the year end (12,1,2,3), so a single calendarRange
    # cannot express it — OR the months together instead.
    dry = ee.Filter.Or(*[ee.Filter.calendarRange(m, m, "month") for m in DRY_MONTHS])

    col = (ee.ImageCollection("COPERNICUS/S2_SR_HARMONIZED")
           .filterBounds(ee.Geometry.Rectangle(GUINEA_BBOX, None, False))
           .filterDate(f"{COMPOSITE_YEARS[0]}-01-01", f"{COMPOSITE_YEARS[1]}-12-31")
           .filter(dry)
           .filter(ee.Filter.lt("CLOUDY_PIXEL_PERCENTAGE", 60))
           .map(mask_land_clear))

    return col.select(S2_BANDS).median(), col


