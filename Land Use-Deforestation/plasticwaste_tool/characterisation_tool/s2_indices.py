def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    print("=" * 74)
    print("Sentinel-2 terrestrial plastic indices at labelled dumpsites")
    print("=" * 74)

    if not init_gee_project_convention():
        print("GEE init failed — aborting.")
        return 1
    import ee

    points = load_points()
    n_pos = sum(1 for p in points if p["label"] == 1)
    print(f"\nPoints: {len(points)}  ({n_pos} positive dump points, "
          f"{len(points) - n_pos} negative cell centroids)")

    composite, col = build_dry_season_composite()
    n_scenes = col.size().getInfo()
    print(f"Dry-season composite: {n_scenes} scenes "
          f"(months {DRY_MONTHS}, {COMPOSITE_YEARS[0]}-{COMPOSITE_YEARS[1]}, "
          f"SCL clear-land classes {SCL_CLEAR_LAND})")

    meta = pd.DataFrame(points)
    frames = []
    for radius in FOOTPRINTS_M:
        label = "native_pixel" if radius == 0 else f"{radius * 2}m_box"
        print(f"\n  extracting footprint: {label}")
        vals = extract(points, composite, radius)
        merged = meta.merge(vals, on="point_id", how="left")
        merged["footprint"] = label
        merged["footprint_radius_m"] = radius
        frames.append(add_indices(merged))

    df = pd.concat(frames, ignore_index=True)
    out_csv = OUT_DIR / "s2_index_samples.csv"
    df.to_csv(out_csv, index=False)

    print(f"\nWrote {len(df)} rows to {out_csv}")
    print("\nNon-null band coverage by footprint:")
    for fp, g in df.groupby("footprint"):
        ok = g["B11"].notna().sum()
        print(f"  {fp:<14} {ok}/{len(g)} points have B11 "
              f"({g[g.label == 1]['B11'].notna().sum()} of "
              f"{(g.label == 1).sum()} positives)")
    return 0


