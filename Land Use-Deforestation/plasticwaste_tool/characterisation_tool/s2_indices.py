"""
11 — Extract Sentinel-2 terrestrial plastic indices at labelled dumpsites.

Task 2 of `docs/DPWMS_Plastic_Characterisation_Plan.md` §7. This script only
EXTRACTS; `12_evaluate_s2_indices.py` does the statistics. They are separate
because extraction is slow and GEE-bound while evaluation is fast and gets
iterated on.

WHAT THIS TEST IS FOR
---------------------
It is a **falsification test**, not a demonstration. The plastic-mulch indices
(PMLI, PGI and relatives) were built to find large uniform plastic sheeting on
soil. The question here is whether they respond to *heterogeneous mixed waste*
at all. If they cannot separate 111 known dumpsite points from 540 known
negatives, they will not rank plastic content *within* dumps, and Path A should
be abandoned rather than tuned.

Task 1 lowered the prior for this considerably — see
`docs/DPWMS_Hyperspectral_Coverage_Findings.md` §4. Neither diagnostic C-H
absorption feature (1215 nm, 1730 nm) falls inside a Sentinel-2 band; both sit
in gaps. So these indices do not measure C-H absorption. They measure the broad
shape of the SWIR continuum, which plastic sheeting happens to alter. A
negative result here is an expected physical outcome, not an implementation
defect.

TWO DESIGN DECISIONS THAT MATTER
--------------------------------

1. **The SCL cloud mask had to be rewritten for land.** This project's FDI
   module uses `scl_clear_classes = [4, 6, 11]` (vegetation, water, snow) and
   config.py:171 explains it deliberately drops class 5, "not vegetated"
   (bare soil / built-up), because keeping it let urban rooftops leak into the
   floating-debris layer.

   For dumpsite work that mask is exactly backwards: **class 5 is where
   dumpsites live.** Reusing the FDI constant would have silently masked away
   most of the targets and produced a confident null result for the wrong
   reason. This module therefore defines its own terrestrial mask and does not
   import the FDI one.

2. **Footprint is tested, not assumed.** The dumpsite-detection phase of this
   project found that a 250 m extraction footprint produced a settlement
   detector rather than a dump detector, and that 80 m point-centred crops
   fixed it. The same failure mode applies here, so every point is extracted at
   three footprints (native pixel, 80 m box, 250 m box) and the evaluation
   reports all three rather than picking one in advance.

Run:  python plasticwaste_tool/11_s2_plastic_indices.py
Out:  plasticwaste_tool/runs/s2_plastic_indices/s2_index_samples.csv
"""
