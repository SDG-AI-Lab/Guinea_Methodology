# Extraction
# --------------------------------------------------------------------------

def extract(points: List[Dict[str, Any]], composite, radius_m: int,
            chunk: int = 150) -> pd.DataFrame:
    import ee

    out: List[Dict[str, Any]] = []
    for start in range(0, len(points), chunk):
        batch = points[start:start + chunk]
        feats = []
        for r in batch:
            g = ee.Geometry.Point([r["lon"], r["lat"]])
            if radius_m > 0:
                g = g.buffer(radius_m).bounds()
            feats.append(ee.Feature(g, {"point_id": r["point_id"]}))

        fc = ee.FeatureCollection(feats)
        sampled = composite.reduceRegions(
            collection=fc, reducer=ee.Reducer.mean(), scale=EXTRACT_SCALE_M,
        ).getInfo()

        for f in sampled["features"]:
            props = f["properties"]
            out.append({"point_id": props["point_id"],
                        **{b: props.get(b) for b in S2_BANDS}})
        print(f"    {min(start + chunk, len(points))}/{len(points)}")
        time.sleep(0.2)

    return pd.DataFrame(out)


# --------------------------------------------------------------------------
# Indices — computed locally, not in GEE, so they stay testable and diffable
# --------------------------------------------------------------------------

def add_indices(df: pd.DataFrame) -> pd.DataFrame:
    """
    Sentinel-2 band mapping follows Gungor et al. (2026), J. Agric. Sci.
    (Tarim Bilimleri Dergisi) 32(1):158-176, DOI 10.15832/ankutbd.1728949,
    which tabulates these indices with the explicit note:
    "In Sentinel-2 MSI satellite images; Blue (B2), Green (B3), Red (B4),
    NIR (B8), SWIR1 (B11)."

    Every formula below is transcribed from a published source. Where a source
    is ambiguous it is flagged rather than silently resolved.
    """
    b2, b3, b4 = df["B2"], df["B3"], df["B4"]
    b7, b8, b8a = df["B7"], df["B8"], df["B8A"]
    b11, b12 = df["B11"], df["B12"]

    def nd(a, b):
        return (a - b) / (a + b)

    # NDVI — Rouse et al. (1974). Control, not a plastic index.
    df["NDVI"] = nd(b8, b4)
    # NDBI — Zha et al. (2003). Used as a PGI gate and as a built-up control.
    df["NDBI"] = nd(b11, b8)

    # PMLI — Lu, Di & Ye (2014). (SWIR1 - Red)/(SWIR1 + Red).
    df["PMLI"] = nd(b11, b4)

    # PGI / RPGI — Yang et al. (2017).
    #   PGI  = 100 * (Blue * (NIR - Red)) / (1 - mean(Blue, Green, NIR))
    #   RPGI = 100 * Blue / (1 - mean(Blue, Green, NIR))
    # AMBIGUITY: the published denominator renders as
    # "1 - mean(rho_Blue + rho_Green + rho_NIR)". Read literally that is
    # 1 - (B+G+NIR), but "mean" of three summed terms is conventionally their
    # average. It is implemented as 1 - (B+G+NIR)/3. Both readings are recorded
    # so the choice is visible; PGI_altdenom carries the literal reading.
    mean_bgn = (b2 + b3 + b8) / 3.0
    df["PGI"] = 100.0 * (b2 * (b8 - b4)) / (1.0 - mean_bgn)
    df["RPGI"] = 100.0 * b2 / (1.0 - mean_bgn)
    df["PGI_altdenom"] = 100.0 * (b2 * (b8 - b4)) / (1.0 - (b2 + b3 + b8))

    # Yang et al. gate PGI to zero outside the plastic-plausible range.
    df.loc[df["NDVI"] > 0.73, "PGI"] = 0.0
    df.loc[df["NDBI"] > 0.005, "PGI"] = 0.0

    # Vi — Greenhouse Vegetable Land Extraction Index, Zhao GengXing et al. (2004)
    df["Vi"] = nd(b11, b8) * nd(b8, b4)

    # PMLI_NIR / PMLI_SWIR / PMLI_ND — Hasituya et al. (2019),
    # Remote Sens. 11(11):1353. D = (NIRn + NIRb + RE3) - (SWIR1 + SWIR2),
    # divided by the NIR sum, the SWIR sum, and all five bands respectively.
    # NIRn/NIRb are read as B8A (narrow) and B8 (broad); RE3 is B7.
    nir_sum = b8a + b8 + b7
    swir_sum = b11 + b12
    d = nir_sum - swir_sum
    df["PMLI_NIR"] = d / nir_sum
    df["PMLI_SWIR"] = d / swir_sum
    df["PMLI_ND"] = d / (nir_sum + swir_sum)

    # NOT IMPLEMENTED: GDI (Greenhouse Detection Index). Its exact formula
    # could not be obtained from an open source, and attribution is disputed
    # between Aguilar et al. (2016) and Gonzalez-Yebra et al. (2018). It is
    # left out rather than guessed. Documented in the findings write-up.
    return df


