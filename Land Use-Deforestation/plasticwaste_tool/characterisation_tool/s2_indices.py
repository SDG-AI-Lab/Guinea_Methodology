def load_points() -> List[Dict[str, Any]]:
    """
    Positives use the annotator's explicit dump coordinates; negatives use the
    cell centroid because they contain no dump to point at.

    That asymmetry is intentional and worth stating: the positive sample asks
    "what does the index read ON a dump", the negative asks "what does it read
    in a cell with no dump". It is the right framing for a detection test, but
    it does mean positives are centred on a chosen object while negatives are
    not centred on anything in particular.
    """
    with open(LABELS_PATH, "r", encoding="utf-8") as fh:
        gj = json.load(fh)

    rows: List[Dict[str, Any]] = []
    for feat in gj["features"]:
        p = feat["properties"]
        label = str(p.get("label", ""))
        tile_id, region = str(p.get("tile_id")), str(p.get("region"))

        if label == "1" and p.get("lat") and p.get("long"):
            lats = [s.strip() for s in str(p["lat"]).split(";") if s.strip()]
            lons = [s.strip() for s in str(p["long"]).split(";") if s.strip()]
            if len(lats) != len(lons):
                print(f"  ! {tile_id}: {len(lats)} lats vs {len(lons)} lons — skipped")
                continue
            for i, (la, lo) in enumerate(zip(lats, lons)):
                rows.append({"point_id": f"{tile_id}_p{i}", "tile_id": tile_id,
                             "region": region, "label": 1,
                             "lon": float(lo), "lat": float(la)})
        elif label == "0":
            coords = feat["geometry"]["coordinates"][0]
            xs = [c[0] for c in coords]
            ys = [c[1] for c in coords]
            rows.append({"point_id": f"{tile_id}_c", "tile_id": tile_id,
                         "region": region, "label": 0,
                         "lon": sum(xs) / len(xs), "lat": sum(ys) / len(ys)})
    return rows


