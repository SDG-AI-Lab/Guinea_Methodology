SCL_CLEAR_LAND = [4, 5, 7]

# Dry season. Guinea's rains run roughly May-October; December-March is when
# Sentinel-2 actually sees the ground. Multi-year median for robustness.
DRY_MONTHS = [12, 1, 2, 3]
COMPOSITE_YEARS = (2023, 2025)

# Extraction footprints, in metres of RADIUS. 0 = the single native pixel.
# 40 m -> 80 m box (the footprint validated for dumpsite detection)
