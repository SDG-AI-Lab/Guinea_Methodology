from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np
import pandas as pd
from sklearn.decomposition import PCA
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

HERE = Path(__file__).resolve().parent
# One level deeper than the numbered original: `runs/`,
# `manual_qa/` and the frozen models all live in the parent
# package directory, so paths climb one extra level.
TOOL = HERE.parent
RUN = TOOL / "runs" / "enmap_spectra"

# EnMAP L2A returns physically impossible reflectance in the deep water-vapour
# windows (bands 1343-1390 nm were 100% negative in the first scene). Drop both.
BAD_WINDOWS = ((1340, 1460), (1800, 1960))
CH_FEATURES = (1215, 1730)
N_BOOT = 2000
RNG_SEED = 0
PCA_COMPONENTS = 10


def load() -> tuple:
    d = np.load(RUN / "spectra.npz", allow_pickle=True)
    S, wl = d["spectra"], d["wavelengths"]
    pts = pd.read_csv(RUN / "points.csv")
    bad = np.zeros(len(wl), dtype=bool)
    for lo, hi in BAD_WINDOWS:
        bad |= (wl >= lo) & (wl <= hi)
    return S[:, ~bad], wl[~bad], pts


def per_band_ap(X: np.ndarray, y: np.ndarray) -> np.ndarray:
    """Orientation-free per-band AP (an index may separate either way)."""
    return np.array([max(average_precision_score(y, X[:, i]),
                         average_precision_score(y, -X[:, i]))
                     for i in range(X.shape[1])])


def cluster_boot(tiles: np.ndarray, rng, n_boot: int) -> List[np.ndarray]:
    uniq = np.unique(tiles)
    by = {t: np.flatnonzero(tiles == t) for t in uniq}
    return [np.concatenate([by[t] for t in rng.choice(uniq, len(uniq), replace=True)])
            for _ in range(n_boot)]


def blocked_multivariate(X: np.ndarray, y: np.ndarray, tiles: np.ndarray,
                         shape_only: bool = False) -> Optional[Dict]:
    """Leave-one-dumpsite-out. Blocks on tile_id so a site never spans folds."""
    if shape_only:
        X = X / X.mean(1, keepdims=True)
    oof = np.full(len(y), np.nan)
    for t in np.unique(tiles):
        te = tiles == t
        tr = ~te
        if y[tr].sum() < 3 or len(np.unique(y[tr])) < 2:
            continue
        n_comp = min(PCA_COMPONENTS, tr.sum() - 1, X.shape[1])
        if n_comp < 2:
            continue
        mdl = make_pipeline(StandardScaler(), PCA(n_components=n_comp, random_state=0),
                            LogisticRegression(max_iter=3000, class_weight="balanced"))
        mdl.fit(X[tr], y[tr])
        oof[te] = mdl.predict_proba(X[te])[:, 1]
    v = np.isfinite(oof)
    if v.sum() < 30 or len(np.unique(y[v])) < 2:
        return None
    base = float(y[v].mean())
    ap = float(average_precision_score(y[v], oof[v]))
    return {"n": int(v.sum()), "baseline": base, "oof_ap": ap,
            "lift": ap / base if base else float("nan")}


def analyse(S, wl, pts, mask: np.ndarray, label: str,
            control: str = "ring_control", boot: bool = True) -> Optional[Dict]:
    sub = pts[mask]
    sel = sub["kind"].isin(["dump", control]).to_numpy()
    idx = np.flatnonzero(mask)[sel]
    if idx.size == 0:
        return None
    X = S[idx]
    y = (pts["kind"].to_numpy()[idx] == "dump").astype(int)
    tiles = pts["tile_id"].to_numpy()[idx]
    if y.sum() < 5 or (1 - y).sum() < 20:
        return None

    base = float(y.mean())
    raw = per_band_ap(X, y)
    shape = per_band_ap(X / X.mean(1, keepdims=True), y)

    feat = {}
    for f in CH_FEATURES:
        i = int(np.argmin(abs(wl - f)))
        feat[f"{f}nm"] = {
            "raw_ap": float(raw[i]), "raw_rank": int((raw > raw[i]).sum()) + 1,
            "shape_ap": float(shape[i]), "shape_rank": int((shape > shape[i]).sum()) + 1,
            "n_bands": int(len(wl)),
        }

    out = {
        "label": label, "n_spectra": int(len(y)), "n_dump_spectra": int(y.sum()),
        "n_distinct_sites": int(pd.unique(tiles[y == 1]).size),
        "baseline_ap": base,
        "best_raw_ap": float(raw.max()), "best_raw_nm": float(wl[raw.argmax()]),
        "best_raw_lift": float(raw.max() / base),
        "best_shape_ap": float(shape.max()), "best_shape_nm": float(wl[shape.argmax()]),
        "ch_features": feat,
        "multivariate_raw": blocked_multivariate(X, y, tiles, False),
        "multivariate_shape": blocked_multivariate(X, y, tiles, True),
    }

    if boot:
        rng = np.random.default_rng(RNG_SEED)
        bi = cluster_boot(tiles, rng, N_BOOT)
        best = int(raw.argmax())
        reps = np.full(N_BOOT, np.nan)
        for k, ii in enumerate(bi):
            yy = y[ii]
            if yy.sum() < 2 or yy.sum() == len(yy):
                continue
            s = X[ii, best]
            reps[k] = max(average_precision_score(yy, s),
                          average_precision_score(yy, -s))
        d = reps[np.isfinite(reps)] - base
        if d.size > 100:
            lo, hi = np.percentile(d, [2.5, 97.5])
            out["best_band_minus_baseline"] = {
                "delta_ap": float(d.mean()), "ci95": [float(lo), float(hi)],
                "excludes_zero": bool(lo > 0)}
    return out


def main() -> int:
    if not (RUN / "spectra.npz").exists():
        print("No spectra — run 18_enmap_extract_spectra.py first.")
        return 1

    S, wl, pts = load()
    scenes = sorted(pts["scene"].unique())
    print("=" * 78)
    print("Gate 4 — EnMAP separability, dumpsites vs their own surroundings")
    print("=" * 78)
    print(f"\n{len(S)} spectra x {len(wl)} usable bands, {len(scenes)} scene(s)")
    print(f"distinct dumpsites (label cells): "
          f"{pts[pts.kind=='dump']['tile_id'].nunique()}")

    results = {"n_bands": int(len(wl)), "bad_windows_nm": BAD_WINDOWS,
               "per_scene": {}, "pooled": None}

    print(f"\n{'-'*78}\nPER SCENE — does the null hold on every acquisition?\n{'-'*78}")
    hdr = (f"  {'scene':<26}{'sites':>6}{'dump':>6}{'base':>7}{'bestAP':>8}"
           f"{'lift':>6}{'multiAP':>9}{'lift':>6}")
    print(hdr)
    for sc in scenes:
        r = analyse(S, wl, pts, (pts["scene"] == sc).to_numpy(), sc, boot=False)
        if r is None:
            print(f"  {sc[:24]:<26}  (too few points)")
            continue
        results["per_scene"][sc] = r
        mv = r["multivariate_raw"] or {}
        print(f"  {sc.split('-')[-1][:24]:<26}{r['n_distinct_sites']:>6}"
              f"{r['n_dump_spectra']:>6}{r['baseline_ap']:>7.3f}"
              f"{r['best_raw_ap']:>8.3f}{r['best_raw_lift']:>6.2f}"
              f"{mv.get('oof_ap', float('nan')):>9.3f}{mv.get('lift', float('nan')):>6.2f}")

    print(f"\n{'-'*78}\nPOOLED — all scenes, blocked on dumpsite\n{'-'*78}")
    pooled = analyse(S, wl, pts, np.ones(len(pts), bool), "pooled", boot=True)
    results["pooled"] = pooled
    if pooled:
        print(f"  spectra {pooled['n_spectra']}  dump spectra "
              f"{pooled['n_dump_spectra']}  DISTINCT SITES {pooled['n_distinct_sites']}")
        print(f"  baseline AP              {pooled['baseline_ap']:.3f}")
        print(f"  best single band         {pooled['best_raw_ap']:.3f} "
              f"at {pooled['best_raw_nm']:.0f} nm  (lift {pooled['best_raw_lift']:.2f})")
        b = pooled.get("best_band_minus_baseline")
        if b:
            print(f"    vs baseline            dAP={b['delta_ap']:+.3f} "
                  f"[{b['ci95'][0]:+.3f}, {b['ci95'][1]:+.3f}]  "
                  f"{'SIGNIFICANT' if b['excludes_zero'] else 'not significant'}")
        for nm, key in (("raw", "multivariate_raw"), ("shape-only", "multivariate_shape")):
            mv = pooled[key]
            if mv:
                print(f"  multivariate ({nm:<10}) OOF AP {mv['oof_ap']:.3f}  "
                      f"baseline {mv['baseline']:.3f}  lift {mv['lift']:.2f}")

        print(f"\n  C-H features (rank among {len(wl)} bands):")
        for f, v in pooled["ch_features"].items():
            print(f"    {f:>8}  raw AP {v['raw_ap']:.3f} rank {v['raw_rank']:>3}"
                  f"   |  brightness removed: AP {v['shape_ap']:.3f} "
                  f"rank {v['shape_rank']:>3}")

    with open(RUN / "separability.json", "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=2)
    print(f"\nWritten to {RUN / 'separability.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
