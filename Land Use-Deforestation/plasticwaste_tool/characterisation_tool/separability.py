"""
20 — Is there ANY spectral separability between dumpsites and their surroundings?

Gate 4's statistics, computed over every downloaded EnMAP scene. Script 18
extracts spectra; this one decides. The notebook presents the result.

WHY THIS EXISTS SEPARATELY FROM THE NOTEBOOK
--------------------------------------------
The first run of gate 4 used a single scene (38 dump spectra). The conclusion —
no C-H signature, near-chance separability — is consequential enough that
"you tested one scene" is a fair criticism, so the test now runs over several
scenes and reports **per-scene** as well as pooled.

WHAT MULTIPLE SCENES DO AND DO NOT BUY
--------------------------------------
Mostly they buy **replication**, not sample size. The scenes with the most dump
points are all over Conakry and largely re-image the SAME sites on different
dates. That is still the right robustness check — if the null holds
independently on five acquisitions across four regions and three years, it is
not a fluke of one atmosphere, one date or one city — but it must not be
reported as "n went from 38 to 150 independent dumpsites". Distinct *sites* are
counted separately from spectra throughout.

BLOCKING
--------
A site appearing in three scenes is one site, not three. All cross-validation
blocks on `tile_id` (the label cell), so every spectrum of a given dumpsite —
across every scene and date — lands in the same fold. Blocking on scene or on
row index would leak a site between train and test and inflate the result.

THE TWO QUESTIONS, KEPT SEPARATE
--------------------------------
  1. Is there ANY separability?          -> AP vs baseline, per band and multivariate
  2. Is it at the C-H features?           -> rank of 1215/1730 nm, before and after
                                             removing brightness

A "yes" to 1 with a "no" to 2 means bare ground again, which is what every
earlier gate found by a different route.

Run:  python plasticwaste_tool/20_enmap_separability.py
Out:  plasticwaste_tool/runs/enmap_spectra/separability.json
"""
